require "cybertrain/generator/helper_scan"

module Cybertrain
  module Gen
    # Writes gen/helpers.rb (spec 3.1): ApplicationHelpers, the
    # Template::Helpers subclass that includes every app/helpers module and
    # dispatches a template's receiverless call to them through a `case`
    # on the literal name (Spinel has no `send`, spikes/NOTES.md rule 1),
    # then installs it as Views.helpers_builder.
    #
    # An optional parameter keeps Ruby's meaning (an omitted one gets the
    # method's own default): one arm per subset of the optional parameters
    # the template passed, the most complete first. A `&block` parameter
    # receives a block returning the template block's output as a
    # SafeString ("" when the template passed none).
    module HelpersEmitter
      HEADER = "# Generated by `spin run gen` from app/helpers. Do not edit.\n"

      def self.emit(modules)
        out = +""
        out << HEADER
        out << "class ApplicationHelpers < Cybertrain::Template::Helpers\n"
        out << "  include ::Gen::UrlHelpers\n"
        modules.each { |m| out << "  include ::#{m.name}\n" }
        out << "\n"
        out << "  def app_helper_call(name, args, kwargs, block, interp, env)\n"
        defs = Array.new(0) { HelperDef.new("", 0, [], [], [], [], "") }
        modules.each { |m| m.defs.each { |d| defs << d } }
        if defs.empty?
          out << "    super(name, args, kwargs, block, interp, env)\n"
        else
          out << "    case name\n"
          defs.each { |d| out << def_arm(d) }
          out << "    else super(name, args, kwargs, block, interp, env)\n"
          out << "    end\n"
        end
        out << "  end\n"
        out << "end\n"
        out << "\n"
        out << "Cybertrain::Views.helpers_builder = ->(controller) { ApplicationHelpers.new(controller) }\n"
        out
      end

      # The `when "name"` arm: the argument checks, then the call. checks:
      # the receiver of the check methods with its dot ("" for the helpers'
      # own; ControllersEmitter's helper_method arms, in a controller, pass
      # "Cybertrain::Template::Helpers.").
      def self.def_arm(d, checks = "")
        out = +""
        min = d.required.size
        max = min + d.optional.size
        out << "    when #{literal(d.name)}\n"
        out << "      #{checks}helper_arity!(name, args, #{min}, #{max})\n"
        if d.keywords_required.empty? && d.keywords_optional.empty?
          out << "      #{checks}helper_no_keywords!(name, kwargs)\n"
        else
          known = d.keywords_required + d.keywords_optional
          out << "      #{checks}helper_keywords!(name, kwargs, [#{known.map { |k| literal(k) }.join(", ")}], #{d.keywords_required.size})\n"
        end
        givens = arm_givens(d)
        keysets = arm_keysets(d)
        if givens.size == 1
          out << "      #{call_source(d, givens[0], keysets[0])}\n"
          return out
        end
        givens.each_with_index do |given, i|
          keys = keysets[i]
          if i == 0
            out << "      if #{condition(d, given, keys)} then #{call_source(d, given, keys)}\n"
          elsif i == givens.size - 1
            out << "      else #{call_source(d, given, keys)}\n"
          else
            out << "      elsif #{condition(d, given, keys)} then #{call_source(d, given, keys)}\n"
          end
        end
        out << "      end\n"
        out
      end

      # Each arm as [optional positionals present, optional keywords
      # present], most complete first: positionals by count (only a prefix
      # can be given), keywords by subset (the first keyword is the highest
      # bit, so "both, unit, precision, none").
      # (Two parallel Arrays rather than pairs: a mixed [Integer, Array]
      # pair is a polymorphic Array under Spinel.)
      def self.arm_givens(d)
        givens = Array.new(0) { 0 }
        d.optional.size.downto(0) do |given|
          ((1 << d.keywords_optional.size) - 1).downto(0) { |_mask| givens << given }
        end
        givens
      end

      def self.arm_keysets(d)
        sets = Array.new(0) { Array.new(0) { "" } }
        q = d.keywords_optional.size
        d.optional.size.downto(0) do |_given|
          ((1 << q) - 1).downto(0) do |mask|
            keys = Array.new(0) { "" }
            d.keywords_optional.each_with_index do |k, i|
              keys << k if mask & (1 << (q - 1 - i)) != 0
            end
            sets << keys
          end
        end
        sets
      end

      def self.condition(d, given, keys)
        parts = Array.new(0) { "" }
        parts << "args.size >= #{d.required.size + given}" if given > 0
        keys.each { |k| parts << "kwargs.key?(#{literal(k)})" }
        parts.join(" && ")
      end

      def self.call_source(d, given, keys)
        args = Array.new(0) { "" }
        (d.required.size + given).times { |i| args << "args[#{i}]" }
        d.keywords_required.each { |k| args << "#{k}: kwargs[#{literal(k)}]" }
        keys.each { |k| args << "#{k}: kwargs[#{literal(k)}]" }
        call = args.empty? ? d.name : "#{d.name}(#{args.join(", ")})"
        # Only when the template passed a block, so `block_given?` in the
        # helper answers as in Ruby.
        call = "block.nil? ? #{call} : #{call} { app_block_content(block, interp, env) }" if d.block?
        call
      end

      def self.literal(text)
        "\"#{text}\""
      end
    end
  end
end

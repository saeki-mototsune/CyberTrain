require "cybertrain/generator/source_text"
require "cybertrain/generator/mailer_scan"

module Cybertrain
  module Gen
    # Writes gen/mailers.rb (docs/design.md D98): per mailer class the
    # reopened class with what Cybertrain::Mailer::Base's `mail` reads
    # (`mailer_class_name`, `mailer_path`, the declared `mailer_layout` and
    # `mailer_default_from`, and `view_assigns` over the instance
    # variables of the class and its mailer ancestors), then for each
    # action a class method of the same name and parameters, and
    # `self.with(params)`, which answers the class's `Parameterized`
    # (written here too) whose methods run the action with those params (a
    # class without actions, ApplicationMailer, gets neither).
    # Every one of them answers the action's Cybertrain::MailMessage:
    # Spinel has no method_missing, so Rails' `UserMailer.welcome(user)`
    # and `UserMailer.with(user: u).welcome` are this code.
    module MailersEmitter
      HEADER = "# Generated by `spin run gen` from app/mailers. Do not edit.\n"
      PATH = "gen/mailers.rb"

      def self.emit(infos)
        out = +""
        out << HEADER
        infos.each do |info|
          out << "\n"
          out << class_source(info, infos)
        end
        out
      end

      def self.class_source(info, infos)
        parts = info.mailer_name.split("::")
        superclass = info.mailer_super
        return plain_class_source(info, infos, info.mailer_name, superclass) if parts.size < 2

        superclass = "::#{superclass}" unless superclass.start_with?("::")
        body = plain_class_source(info, infos, parts.last.to_s, superclass)
        SourceText.wrap_in_scopes(info.mailer_name, info.mailer_scopes, body)
      end

      # The instance variables of the class, then each ancestor's, once each.
      def self.ivars_of(info, infos)
        names = Array.new(0) { "" }
        info.mailer_ivars.each { |n| names << n unless names.include?(n) }
        MailerScan.ancestors(info, infos).each { |a| a.mailer_ivars.each { |n| names << n unless names.include?(n) } }
        names
      end

      def self.plain_class_source(info, infos, name, superclass)
        full = info.mailer_name
        out = +""
        out << "class #{name} < #{superclass}\n"
        out << "  def mailer_class_name\n"
        out << "    #{full.inspect}\n"
        out << "  end\n"
        out << "\n"
        out << "  def mailer_path\n"
        out << "    #{MailerScan.view_path(full).inspect}\n"
        out << "  end\n"
        if info.mailer_layout_declared
          out << "\n"
          out << "  def mailer_layout\n"
          out << "    #{info.mailer_layout_name.inspect}\n"
          out << "  end\n"
        end
        unless info.mailer_from == ""
          out << "\n"
          out << "  # default from:, read each time a mail is built.\n"
          out << "  def mailer_default_from\n"
          out << "    (#{info.mailer_from}).to_s\n"
          out << "  end\n"
        end
        out << "\n"
        out << view_assigns_source(ivars_of(info, infos))
        return out << "end\n" if info.mailer_actions.empty?

        out << "\n"
        out << "  # #{name}.with(key: value).action: the action with those params.\n"
        out << "  class Parameterized\n"
        out << "    def initialize(params)\n"
        out << "      @params = params\n"
        out << "    end\n"
        info.mailer_actions.each do |a|
          out << "\n"
          out << "    def #{a.action_name}#{signature(a)}\n"
          out << "      mailer = #{full}.new\n"
          out << "      mailer.mailer_setup(@params, #{a.action_name.inspect})\n"
          out << "      mailer.#{a.action_name}#{call_args(a)}\n"
          out << "      mailer.mailer_result\n"
          out << "    end\n"
        end
        out << "  end\n"
        out << "\n"
        out << "  def self.with(params)\n"
        out << "    Parameterized.new(params)\n"
        out << "  end\n"
        info.mailer_actions.each do |a|
          out << "\n"
          out << "  def self.#{a.action_name}#{signature(a)}\n"
          out << "    with({}).#{a.action_name}#{call_args(a)}\n"
          out << "  end\n"
        end
        out << "end\n"
        out
      end

      def self.signature(a)
        a.action_params == "" ? "" : "(#{a.action_params})"
      end

      def self.call_args(a)
        a.action_args == "" ? "" : "(#{a.action_args})"
      end

      def self.view_assigns_source(ivars)
        out = +""
        out << "  def view_assigns\n"
        if ivars.empty?
          out << "    Cybertrain::Cast.empty_hash\n"
        else
          pairs = Array.new(0) { "" }
          ivars.each { |n| pairs << "#{n.inspect} => @#{n}" }
          out << "    { #{pairs.join(", ")} }\n"
        end
        out << "  end\n"
        out
      end
    end
  end
end

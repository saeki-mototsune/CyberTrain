require "cybertrain/generator/controller_scan"
require "cybertrain/generator/concern_scan"
require "cybertrain/generator/model_scan"
require "cybertrain/generator/job_scan"

module Cybertrain
  module Gen
    # Writes gen/app.rb, the one file an app's binaries require to load
    # everything: generated models, routes, assets and locales, the app's helpers and
    # components with their generated tables, the console tables, the
    # generated controllers, then the app's own models, jobs
    # (application_job first) with their generated half (gen/jobs.rb), and
    # controllers (application_controller first), and last gen/concerns.rb.
    # The concerns (app/models/concerns, app/controllers/concerns) come
    # before the models and the controllers that include them, loaded from
    # gen/concerns/<path under app/> (ConcernsEmitter.module_files: their
    # `included` and `class_methods` blocks blanked, spikes/NOTES.md rule
    # 92); a file of a concerns directory that opens no module is loaded
    # from app/ after them. When a job's retry_on /
    # discard_on names a framework exception class, the file defining it
    # is required first (the job's class body evaluates the constant, and
    # `require "cybertrain"` does not load the mailer or the HTTP client).
    # When a model declares `encrypts`, it
    # first sets Config.encryption_required, so boot fails without
    # CYBERTRAIN_ENCRYPTION_KEY (cybertrain/encryptor, and with it openssl,
    # is in every program: `require "cybertrain"` loads it for the
    # encrypted session).
    module Manifest
      def self.emit(root)
        emit_with_models(root, rb_files(root, "gen/models"))
      end

      # The same manifest, listing `model_files` ("gen/models/post", sorted)
      # instead of whatever gen/models holds on disk: Runner passes the
      # files the schema calls for, so --check sees a manifest change for a
      # table that was added or dropped before gen/models is rewritten.
      def self.emit_with_models(root, model_files)
        lines = []
        model_files.each { |f| lines << f.delete_prefix("gen/") }
        lines << "routes"
        lines << "assets"
        lines << "locales"
        # The helper modules before gen/helpers (ApplicationHelpers
        # includes them), the component classes before gen/components
        # (which reopens them), ApplicationComponent first.
        rb_files(root, "app/helpers").each { |f| lines << "../#{f}" }
        lines << "helpers"
        components = rb_files(root, "app/components")
        base = "app/components/application_component"
        lines << "../#{base}" if components.include?(base)
        components.each { |f| lines << "../#{f}" unless f == base }
        lines << "components"
        lines << "console"
        lines << "controllers"
        model_concerns = concern_files(root, "app/models")
        model_concerns.each { |f| lines << "concerns/#{f.delete_prefix("app/")}" }
        loose = loose_files(root, "app/models", model_concerns)
        loose.each { |f| lines << "../#{f}" }
        rb_files(root, "app/models").each { |f| lines << "../#{f}" unless model_concerns.include?(f) || loose.include?(f) }
        jobs = rb_files(root, "app/jobs")
        job_base = "app/jobs/application_job"
        lines << "../#{job_base}" if jobs.include?(job_base)
        jobs.each { |f| lines << "../#{f}" unless f == job_base }
        lines << "jobs"
        # The concerns before the classes that include them, each after
        # the concerns it includes.
        concerns = concern_files(root, "app/controllers")
        concerns.each { |f| lines << "concerns/#{f.delete_prefix("app/")}" }
        loose_controllers = loose_files(root, "app/controllers", concerns)
        loose_controllers.each { |f| lines << "../#{f}" }
        controllers = rb_files(root, "app/controllers")
        first = "app/controllers/application_controller"
        lines << "../#{first}" if controllers.include?(first)
        controllers.each { |f| lines << "../#{f}" unless f == first || concerns.include?(f) || loose_controllers.include?(f) }
        # Last: it reopens the application's classes (concerns, plan
        # decision 8).
        lines << "concerns"

        out = +"# Generated by `spin run gen`. Do not edit.\n"
        if encrypts_declared?(root)
          out << "# A model declares `encrypts`: boot requires CYBERTRAIN_ENCRYPTION_KEY.\n"
          out << "Cybertrain::Config.encryption_required = true\n"
        end
        JobScan.framework_files(JobScan.scan_dir("#{root}/app/jobs")).each do |file|
          out << "require \"cybertrain/#{file}\"\n"
        end
        lines.each { |l| out << "require_relative \"#{l}\"\n" }
        out
      end

      # Whether a file of root/app/models has an `encrypts` line.
      def self.encrypts_declared?(root)
        ModelScan.scan_dir("#{root}/app/models").each { |info| return true unless info.encrypted.empty? }
        false
      end

      # "app/models/post" for root/app/models/post.rb, sorted.
      def self.rb_files(root, dir)
        ControllerScan.ruby_files("#{root}/#{dir}").map { |path| relative(root, path) }
      end

      def self.relative(root, path)
        base = "#{root}/"
        rel = path.start_with?(base) ? path[base.size, path.size - base.size].to_s : path
        rel.delete_suffix(".rb")
      end

      # The concern files of root/dir (dir/concerns/**, and the module-only
      # files elsewhere under dir): each after the concerns it includes
      # (ConcernScan.expand, depth first).
      def self.concern_files(root, dir)
        infos = ConcernScan.scan_dir("#{root}/#{dir}")
        names = Array.new(0) { "" }
        infos.each { |c| names << c.concern_name }
        files = Array.new(0) { "" }
        ConcernScan.expand(names, infos).each do |c|
          rel = relative(root, c.concern_file)
          files << rel unless files.include?(rel)
        end
        files
      end

      # The files of root/dir/concerns that are not concerns (they open no
      # module), sorted.
      def self.loose_files(root, dir, concerns)
        files = Array.new(0) { "" }
        rb_files(root, "#{dir}/concerns").each { |f| files << f unless concerns.include?(f) }
        files
      end
    end
  end
end

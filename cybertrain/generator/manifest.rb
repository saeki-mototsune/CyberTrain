require "cybertrain/generator/controller_scan"
require "cybertrain/generator/model_scan"
require "cybertrain/generator/job_scan"

module Cybertrain
  module Gen
    # Writes gen/app.rb, the one file an app's binaries require to load
    # everything: generated models and routes, the app's helpers and
    # components with their generated tables, the console tables, the
    # generated controllers, then the app's own models, jobs
    # (application_job first) with their generated half (gen/jobs.rb), and
    # controllers (application_controller first). When a job's retry_on /
    # discard_on names a framework exception class, the file defining it
    # is required first (the job's class body evaluates the constant, and
    # `require "cybertrain"` does not load the mailer or the HTTP client).
    # When a model declares `encrypts`, it
    # first requires cybertrain/encryptor (which links openssl, so an app
    # without encrypted columns does not) and sets
    # Config.encryption_required, so boot fails without
    # CYBERTRAIN_ENCRYPTION_KEY.
    module Manifest
      def self.emit(root)
        emit_with_models(root, rb_files(root, "gen/models"))
      end

      # The same manifest, listing `model_files` ("gen/models/post", sorted)
      # instead of whatever gen/models holds on disk: Runner passes the
      # files the schema calls for, so --check sees a manifest change for a
      # table that was added or dropped before gen/models is rewritten.
      def self.emit_with_models(root, model_files)
        lines = []
        model_files.each { |f| lines << f.delete_prefix("gen/") }
        lines << "routes"
        # The helper modules before gen/helpers (ApplicationHelpers
        # includes them), the component classes before gen/components
        # (which reopens them), ApplicationComponent first.
        rb_files(root, "app/helpers").each { |f| lines << "../#{f}" }
        lines << "helpers"
        components = rb_files(root, "app/components")
        base = "app/components/application_component"
        lines << "../#{base}" if components.include?(base)
        components.each { |f| lines << "../#{f}" unless f == base }
        lines << "components"
        lines << "console"
        lines << "controllers"
        rb_files(root, "app/models").each { |f| lines << "../#{f}" }
        jobs = rb_files(root, "app/jobs")
        job_base = "app/jobs/application_job"
        lines << "../#{job_base}" if jobs.include?(job_base)
        jobs.each { |f| lines << "../#{f}" unless f == job_base }
        lines << "jobs"
        controllers = rb_files(root, "app/controllers")
        first = "app/controllers/application_controller"
        lines << "../#{first}" if controllers.include?(first)
        controllers.each { |f| lines << "../#{f}" unless f == first }

        out = +"# Generated by `spin run gen`. Do not edit.\n"
        if encrypts_declared?(root)
          out << "# A model declares `encrypts`: link the column encryption (Spinel's\n"
          out << "# openssl package) and make boot require CYBERTRAIN_ENCRYPTION_KEY.\n"
          out << "require \"cybertrain/encryptor\"\n"
          out << "Cybertrain::Config.encryption_required = true\n"
        end
        JobScan.framework_files(JobScan.scan_dir("#{root}/app/jobs")).each do |file|
          out << "require \"cybertrain/#{file}\"\n"
        end
        lines.each { |l| out << "require_relative \"#{l}\"\n" }
        out
      end

      # Whether a file of root/app/models has an `encrypts` line.
      def self.encrypts_declared?(root)
        ModelScan.scan_dir("#{root}/app/models").each { |info| return true unless info.encrypted.empty? }
        false
      end

      # "app/models/post" for root/app/models/post.rb, sorted.
      def self.rb_files(root, dir)
        base = "#{root}/"
        ControllerScan.ruby_files("#{root}/#{dir}").map do |path|
          rel = path.start_with?(base) ? path[base.size, path.size - base.size].to_s : path
          rel.delete_suffix(".rb")
        end
      end
    end
  end
end

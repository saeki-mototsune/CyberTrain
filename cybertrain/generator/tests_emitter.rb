require "cybertrain/test_files"
require "cybertrain/generator/code_view"
require "cybertrain/generator/test_scan"
require "cybertrain/generator/models_emitter"

module Cybertrain
  module Gen
    # gen/tests.rb, the one program `cybertrain test` compiles (spec
    # sections 5.2 and 8): the test environment forced (plan decision 19),
    # the framework, the application and gen's outputs, the helper and
    # test/support/** (or their class-form copies under gen/test/), then
    # every test file in path order, each after `Test.begin_file` (its
    # literal test names and lines, plan decision 10); then Gen::Tests,
    # the table of class-form tests with one `case` arm per test (spec
    # 5.2's four lines; the dispatch lambda is made in a method, rule 82);
    # last the boot, the table handed over, and the runner's exit status.
    #
    # A bundle that cannot be built is refused (pre-flight ruling B2) by a
    # gen/tests.rb that only aborts with the reason, so `spin run gen` and
    # `spin test` keep working and `cybertrain test` fails with it: a
    # top-level `def` or constant defined in two bundled files (they would
    # merge into one in one program), and the block forms that are not
    # offered (plan decision 14).
    module TestsEmitter
      PATH = "gen/tests.rb".freeze
      HEADER = "# gen/tests.rb: every test of the application in one program, compiled and run by\n" \
               "# `cybertrain test`. Generated by `spin run gen` from test/. Do not edit.\n".freeze
      SHARED = "move shared helpers to test/support/ or into a test class".freeze

      # The source of gen/tests.rb for `files` (TestScan.scan(root)); with
      # `data`, gen/test/data.rb (the fixtures) is required and its clear
      # and load registered before every test.
      # @param root [String]
      # @param files [Array<Cybertrain::Gen::TestFile>]
      # @param data [Boolean]
      # @return [String]
      def self.emit(root, files, data)
        problem = refusal(root, files)
        return refused_program(problem) unless problem.empty?

        out = +HEADER
        out << "ENV[\"CYBERTRAIN_ENV\"] = \"test\"\n"
        out << "ENV.delete(\"CYBERTRAIN_DATABASE\")\n"
        out << "ENV[\"CYBERTRAIN_DATABASE\"] = ENV[\"CYBERTRAIN_TEST_DATABASE\"].to_s unless ENV[\"CYBERTRAIN_TEST_DATABASE\"].to_s.empty?\n"
        out << "require \"cybertrain\"\n"
        out << "require \"cybertrain/test_help\"\n"
        out << "require \"cybertrain/test/bundle\"\n"
        out << "require_relative \"../config/app\"\n"
        out << "require_relative \"app\"\n"
        out << "require_relative \"migrations\"\n" if File.directory?("#{root}/db/migrate")
        out << "require_relative \"test/data\"\n" if data
        out << "Cybertrain::Test.bundled!\n"
        files.each { |f| out << "require_relative \"#{required(f)}\"\n" if f.support_file? }
        files.each do |f|
          next if f.support_file?

          out << "Cybertrain::Test.begin_file(#{ModelsEmitter.ruby_string(f.test_path)}, #{names_literal(f)}, #{lines_literal(f)})\n"
          out << "require_relative \"#{required(f)}\"\n"
        end
        out << "\n"
        out << table(files, data)
        out << "\n"
        out << "Cybertrain::Test::Bundle.boot!(Gen::Routes.build(Cybertrain::Router.new), Gen::Routes.url_resolver)\n"
        out << "Cybertrain::Test.before_each_bundled(Gen::Tests.fixtures_hook)\n" if data
        out << "Cybertrain::Test::Bundle.use_table(Gen::Tests::FILES, Gen::Tests::CASE_FILE, Gen::Tests::CASE_LINE, " \
               "Gen::Tests::CASE_CLASS, Gen::Tests::CASE_NAME, Gen::Tests::CASE_METHOD)\n"
        out << "exit(Cybertrain::Test::Bundle.run!(ARGV, Gen::Tests.dispatcher))\n"
        out
      end

      # The program written when the bundle is refused: it only aborts.
      def self.refused_program(problem)
        "#{HEADER}abort(#{ModelsEmitter.ruby_string(problem)})\n"
      end

      # What require_relative (from gen/) loads for f: its class-form copy
      # under gen/test/, or the file itself.
      def self.required(f)
        rel = f.copy_path.empty? ? "../#{f.test_path}" : f.copy_path.delete_prefix("gen/")
        rel.delete_suffix(".rb")
      end

      def self.names_literal(f)
        return "Array.new(0) { \"\" }" if f.test_lines.empty?

        parts = Array.new(0) { "" }
        f.test_lines.each { |t| parts << ModelsEmitter.ruby_string(t.case_name) }
        "[#{parts.join(", ")}]"
      end

      def self.lines_literal(f)
        return "Array.new(0) { 0 }" if f.test_lines.empty?

        parts = Array.new(0) { "" }
        f.test_lines.each { |t| parts << t.case_line.to_s }
        "[#{parts.join(", ")}]"
      end

      # module Gen::Tests: FILES (the test files in path order), the
      # parallel CASE_* Arrays of the class-form tests, run_case with one
      # arm per test, dispatcher and (with data) fixtures_hook.
      def self.table(files, data)
        paths = Array.new(0) { "" }
        c_file = Array.new(0) { "" }
        c_line = Array.new(0) { "" }
        c_class = Array.new(0) { "" }
        c_name = Array.new(0) { "" }
        c_method = Array.new(0) { "" }
        arms = +""
        files.each do |f|
          next if f.support_file?

          paths << ModelsEmitter.ruby_string(f.test_path)
          f.test_classes.each do |k|
            k.cases.each do |t|
              arms << "      when #{c_file.length}\n"
              arms << "        t = #{k.class_name}.new\n"
              arms << "        if Cybertrain::Test.before_case(t)\n"
              arms << "          Cybertrain::Test.run_body(t) { t.#{t.case_method} }\n"
              arms << "        end\n"
              arms << "        Cybertrain::Test.after_case(t)\n"
              c_file << ModelsEmitter.ruby_string(f.test_path)
              c_line << t.case_line.to_s
              c_class << ModelsEmitter.ruby_string(k.class_name)
              c_name << ModelsEmitter.ruby_string(t.case_name)
              c_method << ModelsEmitter.ruby_string(t.case_method)
            end
          end
        end
        out = +"module Gen\n  module Tests\n"
        out << "    FILES = #{list(paths, "\"\"")}.freeze\n"
        out << "    CASE_FILE = #{list(c_file, "\"\"")}.freeze\n"
        out << "    CASE_LINE = #{list(c_line, "0")}.freeze\n"
        out << "    CASE_CLASS = #{list(c_class, "\"\"")}.freeze\n"
        out << "    CASE_NAME = #{list(c_name, "\"\"")}.freeze\n"
        out << "    CASE_METHOD = #{list(c_method, "\"\"")}.freeze\n"
        out << "\n"
        out << "    # Runs the class-form test i: spec 5.2's four lines per arm.\n"
        out << "    def self.run_case(i)\n"
        unless arms.empty?
          out << "      case i\n"
          out << arms
          out << "      end\n"
        end
        out << "      nil\n"
        out << "    end\n"
        out << "\n"
        out << "    def self.dispatcher = ->(i) { run_case(i) }\n"
        if data
          out << "\n"
          out << "    # Steps 1-2 of every test: the database cleared, the fixtures loaded.\n"
          out << "    def self.fixtures_hook\n"
          out << "      -> {\n"
          out << "        Cybertrain::Test::Database.clear!(Gen::TestData::TABLES)\n"
          out << "        Cybertrain::Test::Database.load_fixtures!(Gen::TestData::FIXTURE_SQL, Gen::TestData::FIXTURE_TIMESTAMPS)\n"
          out << "        nil\n"
          out << "      }\n"
          out << "    end\n"
        end
        out << "  end\nend\n"
        out
      end

      # An Array literal of the emitted items, or a typed empty Array
      # (spikes/NOTES.md rule 9) seeded with `seed`.
      def self.list(items, seed)
        return "Array.new(0) { #{seed} }" if items.empty?

        "[#{items.join(", ")}]"
      end

      # ---- refusals ----

      # Why the bundle cannot be built ("" when it can): a top-level `def`
      # or constant defined in two bundled files, then a block form that is
      # not offered, each as "<path>:<line>: ...".
      # @return [String]
      def self.refusal(root, files)
        problem = duplicate(files)
        return problem unless problem.empty?

        k = 0
        while k < files.length
          f = files[k]
          found = block_form(f.test_path, File.read("#{root}/#{f.test_path}"))
          return found unless found.empty?

          k += 1
        end
        ""
      end

      # The first top-level helper (in scan order) that an earlier file
      # already defines.
      def self.duplicate(files)
        seen = { "" => "" }
        seen.delete("")
        k = 0
        while k < files.length
          f = files[k]
          mine = Array.new(0) { "" }
          j = 0
          while j < f.test_helpers.length
            h = f.test_helpers[j]
            j += 1
            key = "#{h.helper_kind} #{h.helper_name}"
            next if mine.include?(key)

            where = "#{f.test_path}:#{h.helper_line}"
            first = seen[key]
            return "#{where}: #{h.helper_name} is also defined at #{first}; #{SHARED}" unless first.nil?

            mine << key
            seen[key] = where
          end
          k += 1
        end
        ""
      end

      # The first `assert_select ... do` / `{ }` or `render_inline(...) do`
      # / `{ }` of text (plan decision 14), as the refusal; "" for none.
      def self.block_form(path, text)
        view = CodeView.new(text)
        lines = text.lines
        i = 0
        while i < lines.length
          raw = lines[i]
          code = view.codes[i].to_s
          at = word_at(code, "assert_select")
          if at >= 0 && block_after?(code[at + 13, code.length - at - 13].to_s)
            selector = first_argument(raw[at + 13, raw.length - at - 13].to_s)
            return "#{path}:#{i + 1}: assert_select: the nested block form is not supported (selector: #{selector})"
          end
          at = word_at(code, "render_inline")
          if at >= 0 && block_after?(code[at + 13, code.length - at - 13].to_s)
            return "#{path}:#{i + 1}: render_inline: pass the content as content:, not a block"
          end
          i += 1
        end
        ""
      end

      # Where `word` is called in code (not part of a longer name, followed
      # by a space or "("); -1 for nowhere.
      def self.word_at(code, word)
        from = 0
        while from < code.length
          at = code.index(word, from)
          return -1 if at.nil?

          before = at.zero? ? " " : code[at - 1].to_s
          after = code[at + word.length].to_s
          return at if !TestScan.word_char?(before) && before != "." && before != ":" && (after == " " || after == "(")

          from = at + word.length
        end
        -1
      end

      # Whether the rest of a call's line passes a block: it ends in `do`
      # (or `do |x|`), or a `{` follows the closing `)` of its arguments.
      def self.block_after?(rest)
        t = rest.rstrip
        if t.end_with?("|")
          open = t[0, t.length - 1].to_s.rindex("|")
          t = t[0, open].to_s.rstrip unless open.nil?
        end
        return true if t == "do" || t.end_with?(" do") || t.end_with?(")do")

        close = t.index(")")
        while !close.nil?
          after = t[close + 1, t.length - close - 1].to_s.lstrip
          return true if after.start_with?("{")

          close = t.index(")", close + 1)
        end
        false
      end

      # The call's first argument as written: a string literal whole, else
      # up to the first `,`, `)` or ` do`.
      def self.first_argument(rest)
        s = rest.lstrip
        s = s[1, s.length - 1].to_s.lstrip if s.start_with?("(")
        if s.start_with?("\"") || s.start_with?("'")
          q = s[0].to_s
          k = 1
          while k < s.length
            return s[0, k + 1].to_s if s[k] == q

            k += s[k] == "\\" ? 2 : 1
          end
          return s.rstrip
        end
        stop = s.length
        marks = [",", ")", " do", " {"]
        m = 0
        while m < marks.length
          at = s.index(marks[m])
          stop = at if !at.nil? && at < stop
          m += 1
        end
        s[0, stop].to_s.strip
      end
    end
  end
end

require "cybertrain/generator/locale_yaml"
require "cybertrain/generator/views_emitter"

module Cybertrain
  module Gen
    # Writes a dictionary module (gen/locales.rb, plan decision D3; and
    # cybertrain/locales/bundled.rb, D2) from merged LocaleEntry records:
    # `lookup(key)` -> String or nil, `lookup_list(key)` -> Array<String>
    # (empty when absent), and `resolver` / `list_resolver`, the two as
    # lambdas. Texts and lists are two Hash constants, each filled at load
    # by methods of at most FILL_SIZE stores, keys sorted: one literal of
    # every key compiles slowly (spikes/NOTES.md rule 101, spec section 12
    # item 6b). With `install`, the file first requires cybertrain/i18n, so
    # it loads on its own, and its last line hands both lambdas to
    # I18n.install_dictionary (positionally, rule 42).
    module LocalesEmitter
      FILL_SIZE = 50

      def self.emit(entries, module_name = "Gen::Locales", install = true)
        texts = Array.new(0) { LocaleEntry.new("", "", Array.new(0) { "" }, false, "", 0) }
        lists = Array.new(0) { LocaleEntry.new("", "", Array.new(0) { "" }, false, "", 0) }
        entries.sort_by { |e| e.entry_key }.each do |e|
          if e.entry_is_list
            lists << e
          else
            texts << e
          end
        end
        names = module_name.split("::")
        pad = "  " * names.size
        out = +""
        if install
          out << "# Generated by `spin run gen` from config/locales. Do not edit.\n"
          out << "require \"cybertrain/i18n\"\n"
        else
          out << "# Generated by script/bundle-locales from cybertrain/locales. Do not edit.\n"
        end
        out << "\n"
        names.each_with_index { |n, i| out << ("  " * i) << "module " << n << "\n" }
        out << LocalesEmitter.table_source(texts, "texts", "text_table", "{ \"\" => \"\" }", pad)
        out << LocalesEmitter.table_source(lists, "lists", "list_table", "{ \"\" => [\"\"] }", pad)
        out << pad << "TEXTS = " << module_name << ".text_table.freeze\n"
        out << pad << "LISTS = " << module_name << ".list_table.freeze\n\n"
        out << pad << "def self.lookup(key) = TEXTS[key]\n\n"
        out << pad << "def self.lookup_list(key) = LISTS.fetch(key, [])\n\n"
        out << pad << "def self.resolver = ->(key) { " << module_name << ".lookup(key) }\n\n"
        out << pad << "def self.list_resolver = ->(key) { " << module_name << ".lookup_list(key) }\n"
        i = names.size - 1
        while i >= 0
          out << ("  " * i) << "end\n"
          i -= 1
        end
        out << "\nI18n.install_dictionary(#{module_name}.resolver, #{module_name}.list_resolver)\n" if install
        out
      end

      # The fill_<kind>_NN methods of `entries`, then the method answering
      # the Hash they fill, seeded with its value type (rule 9).
      def self.table_source(entries, kind, builder, seed, pad)
        out = +""
        fills = Array.new(0) { "" }
        k = 0
        while k < entries.size
          name = "fill_#{kind}_#{format("%02d", fills.size)}"
          fills << name
          out << pad << "def self." << name << "(h)\n"
          stop = k + FILL_SIZE
          while k < entries.size && k < stop
            e = entries[k]
            out << pad << "  h[" << ViewsEmitter.literal(e.entry_key) << "] = " << LocalesEmitter.value_literal(e) << "\n"
            k += 1
          end
          out << pad << "  nil\n" << pad << "end\n\n"
        end
        out << pad << "def self." << builder << "\n"
        out << pad << "  h = " << seed << "\n"
        out << pad << "  h.delete(\"\")\n"
        fills.each { |f| out << pad << "  " << f << "(h)\n" }
        out << pad << "  h\n" << pad << "end\n\n"
        out
      end

      # An entry's value as a Ruby literal: its text, or its list (an empty
      # one typed, rule 9).
      def self.value_literal(entry)
        return ViewsEmitter.literal(entry.entry_text) unless entry.entry_is_list
        return "Array.new(0) { \"\" }" if entry.entry_list.empty?

        "[#{entry.entry_list.map { |item| ViewsEmitter.literal(item) }.join(", ")}]"
      end
    end
  end
end

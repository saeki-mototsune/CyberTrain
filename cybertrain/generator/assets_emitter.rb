require "cybertrain/generator/asset_scan"
require "cybertrain/generator/importmap_reader"
require "cybertrain/generator/views_emitter"

module Cybertrain
  module Gen
    # Writes gen/assets.rb (spec sections 7.1 and 7.3): Gen::Assets with
    # digest_path (a `case` from logical to digested path, "" for an
    # unknown name), the import map as compact JSON, the preloaded paths,
    # and the resolver handed to Cybertrain::Assets.install. And
    # sync_public, which writes public/assets (`spin run gen` only, never
    # with --check, so gen/assets.rb stays a pure function of the sources).
    module AssetsEmitter
      HEADER = "# Generated by `spin run gen` from app/assets, app/javascript, vendor/javascript and config/importmap.rb. Do not edit.\n"
      MANIFEST = ".manifest"
      KEPT_VERSIONS = 3

      def self.emit(files, pins)
        out = +""
        out << HEADER
        out << "require \"cybertrain/assets\"\n\n"
        out << "module Gen\n"
        out << "  module Assets\n"
        out << "    # \"logo.svg\" -> \"/assets/logo-1a2b3c4d.svg\"; \"\" for a name that is not an asset.\n"
        out << "    def self.digest_path(logical)\n"
        if files.empty?
          out << "      \"\"\n"
        else
          out << "      case logical\n"
          files.each do |f|
            out << "      when #{literal(f.logical_path)} then #{literal("/assets/#{f.digested_path}")}\n"
          end
          out << "      else \"\"\n"
          out << "      end\n"
        end
        out << "    end\n\n"
        out << "    # The import map of config/importmap.rb, as compact JSON.\n"
        out << "    def self.importmap_json\n"
        out << "      #{literal(importmap_json(pins, files))}\n"
        out << "    end\n\n"
        out << "    # The paths javascript_importmap_tags preloads, in pin order.\n"
        out << "    def self.preload_paths\n"
        preloads = preload_list(pins, files)
        if preloads.empty?
          out << "      Array.new(0) { \"\" }\n"
        else
          out << "      [#{preloads.map { |p| literal(p) }.join(", ")}]\n"
        end
        out << "    end\n\n"
        out << "    def self.resolver = ->(name) { digest_path(name) }\n"
        out << "  end\n"
        out << "end\n\n"
        out << "Cybertrain::Assets.install(Gen::Assets.resolver, Gen::Assets.importmap_json, Gen::Assets.preload_paths)\n"
        out
      end

      def self.literal(text)
        ViewsEmitter.literal(text)
      end

      # A pin's URL: its digested path, or the URL it was pinned to.
      def self.pin_path(pin, files)
        return pin.pin_target if pin.pin_url?

        asset = AssetScan.find(files, pin.pin_target)
        asset.nil? ? "" : "/assets/#{asset.digested_path}"
      end

      # {"imports":{"name":"path",...}}, pins in order; `</` is written
      # `\u003c/` so the JSON can sit inside a <script> element.
      def self.importmap_json(pins, files)
        out = +"{\"imports\":{"
        pins.each_with_index do |pin, i|
          out << "," if i > 0
          out << json_string(pin.pin_name) << ":" << json_string(pin_path(pin, files))
        end
        out << "}}"
        out
      end

      def self.preload_list(pins, files)
        paths = Array.new(0) { "" }
        pins.each { |pin| paths << pin_path(pin, files) if pin.pin_preload }
        paths
      end

      def self.json_string(text)
        out = +"\""
        chars = text.chars
        chars.each_with_index do |c, i|
          if c == "\"" then out << "\\\""
          elsif c == "\\" then out << "\\\\"
          elsif c == "<" && i + 1 < chars.size && chars[i + 1] == "/" then out << "\\u003c"
          elsif c.bytesize == 1 && (c.ord < 0x20 || c.ord == 0x7f)
            b = c.ord
            out << "\\u00" << ViewsEmitter::HEX[b / 16] << ViewsEmitter::HEX[b % 16]
          else out << c
          end
        end
        out << "\""
        out
      end

      # Writes each file's digested copy into root/public/assets (a file
      # already there is never rewritten: its name is its content), then
      # rewrites public/assets/.manifest, one `<logical> <current>
      # <previous> <previous>` line per logical path (sorted): the three
      # newest digests are kept and an older one's file is deleted. A line
      # whose asset is gone is kept as it is; a malformed line (a path that
      # could leave public/assets, a digest that is not 8 hex characters)
      # is dropped and deletes nothing. Nothing else under public/assets is
      # touched. Returns the log lines.
      def self.sync_public(root, files)
        log = Array.new(0) { "" }
        dir = "#{root}/public/assets"
        manifest_path = "#{dir}/#{MANIFEST}"
        had_manifest = File.exist?(manifest_path)
        return log if files.empty? && !had_manifest

        kept = had_manifest ? read_manifest(File.read(manifest_path)) : empty_manifest
        files.each do |f|
          unless AssetScan.safe_logical?(f.logical_path)
            message = "asset #{f.source_path}: refusing to write outside public/assets"
            raise ArgumentError, message
          end
          target = "#{dir}/#{f.digested_path}"
          unless File.exist?(target)
            write_new(target, f.asset_body)
            log << "wrote public/assets/#{f.digested_path}"
          end
          digests = Array.new(0) { "" }
          digests << f.asset_digest
          (kept[f.logical_path] || Array.new(0) { "" }).each { |d| digests << d unless digests.include?(d) }
          digests.each_with_index do |d, i|
            next if i < KEPT_VERSIONS

            old = AssetScan.digested_name(f.logical_path, d)
            path = "#{dir}/#{old}"
            next unless File.exist?(path) || File.symlink?(path)

            File.delete(path)
            log << "removed public/assets/#{old}"
          end
          kept[f.logical_path] = digests[0, KEPT_VERSIONS].to_a
        end
        text = +""
        kept.keys.sort.each { |logical| text << logical << " " << kept[logical].join(" ") << "\n" }
        current = had_manifest ? File.read(manifest_path) : ""
        unless current == text
          write_replacing(manifest_path, text)
          log << "wrote public/assets/#{MANIFEST}"
        end
        log
      end

      def self.empty_manifest
        kept = { "" => Array.new(0) { "" } }
        kept.delete("") # a typed empty Hash (spikes/NOTES.md rule 9)
        kept
      end

      # logical => digests (newest first), from a .manifest's text; a
      # malformed line is left out.
      def self.read_manifest(text)
        kept = empty_manifest
        text.each_line do |line|
          parts = line.strip.split(" ")
          next if parts.size < 2

          logical = parts[0].to_s
          next unless AssetScan.safe_logical?(logical)

          digests = Array.new(0) { "" }
          parts.each_with_index { |d, i| digests << d.to_s if i > 0 }
          next unless digests.all? { |d| digest?(d) }

          kept[logical] = digests
        end
        kept
      end

      def self.digest?(text)
        return false unless text.size == 8

        text.each_char { |c| return false unless (c >= "0" && c <= "9") || (c >= "a" && c <= "f") }
        true
      end

      def self.make_dirs(dir)
        return nil if File.directory?(dir)

        make_dirs(File.dirname(dir))
        Dir.mkdir(dir)
        nil
      end

      # Writes a new file through a temporary one renamed into place, so a
      # server reading public/assets never sees half a file and a symlink
      # left at the path is replaced, not followed.
      def self.write_new(path, body)
        make_dirs(File.dirname(path))
        write_replacing(path, body)
      end

      def self.write_replacing(path, body)
        tmp = "#{File.dirname(path)}/.#{File.basename(path)}.#{Process.pid}.tmp"
        File.delete(tmp) if File.exist?(tmp) || File.symlink?(tmp)
        f = File.open(tmp, File::WRONLY | File::CREAT | File::EXCL | File::BINARY, 0o644)
        f.write(body)
        f.close
        File.rename(tmp, path)
        nil
      end
    end
  end
end

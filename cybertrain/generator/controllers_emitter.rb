require "cybertrain/generator/controller_scan"
require "cybertrain/generator/concern_scan"
require "cybertrain/generator/helper_scan"
require "cybertrain/generator/helpers_emitter"
require "cybertrain/generator/routes_dsl"
require "cybertrain/generator/routes_emitter"

module Cybertrain
  module Gen
    # Writes gen/controllers.rb: per controller, view_assigns (the ivars a
    # template can read, including those its scanned parents assign) and a
    # run_callback case table so symbol callbacks dispatch without send.
    # With a jobs page drawn (`jobs_page` in config/routes.rb, passed as
    # jobs_page), CybertrainJobsController comes last. A controller that
    # includes concerns (ConcernScan) gets their callbacks' arms and their
    # ivars too (gen/concerns.rb splices the declarations themselves).
    #
    # A controller that declares `helper_method :x` (or includes a concern
    # whose `included` block does, spec 4.3) gets helper_method?(name) and
    # call_helper_method(name, args, kwargs): a `case` over the names that
    # reaches the controller's method through HelpersEmitter's argument
    # checks and arms, and `super` for the rest, so a parent's helper
    # methods stay callable. A name that the framework's template helpers
    # or the route helpers answer, one an app/helpers module (passed as
    # helper_modules) defines, or one with no `def` in the controller, its
    # scanned parents or its concerns is refused.
    #
    # A controller with `layout` lines (or whose concerns' `included`
    # blocks have them, counted at the `include` line) gets
    # controller_layout(action): the declarations in order, the first that
    # applies to the action winning, else `super` (layout_source).
    module ControllersEmitter
      def self.emit(infos, jobs_page = JobsPageSpec.new("", ""), concerns = Array.new(0) { ConcernInfo.new("", "", 0) },
                    helper_modules = Array.new(0) { HelperModule.new("", "", Array.new(0) { HelperDef.new("", 0, [], [], [], [], "") }) })
        out = +"# Generated by `spin run gen` from app/controllers. Do not edit.\n"
        parents_first(infos).each do |info|
          out << "\n"
          helpers = layout_source(info, infos, concerns) + helper_methods_source(info, infos, concerns, helper_modules) +
                    rate_limit_source(info, infos, concerns)
          out << class_source(info, visible_ivars(info, infos, concerns), callbacks_with_concerns(info, infos, concerns), helpers)
        end
        unless jobs_page.jobs_path.empty?
          out << "\n"
          out << jobs_controller_source(jobs_page)
        end
        out
      end

      # The jobs page's controller: ApplicationController's layout, CSRF
      # protection and helpers apply, behind the before_action jobs_page
      # named. Its actions hand the work to Cybertrain::JobsPage and come
      # back to the page with a flash notice. `retry`, a Ruby keyword, and
      # the others are `<action>_action` methods (the routes say so); their
      # names differ from JobsPage's, which return other types (NOTES rule 10).
      def self.jobs_controller_source(page)
        path = RoutesEmitter.quote(page.jobs_path)
        guard = page.jobs_before_action
        out = +""
        out << "require \"cybertrain/jobs_page\"\n"
        out << "\n"
        out << "# The jobs page (`jobs_page #{path}` in config/routes.rb): the\n"
        out << "# rows in Cybertrain::JobsPage, in the application's layout, behind its\n"
        out << "# before_action and CSRF protection.\n"
        out << "class CybertrainJobsController < ApplicationController\n"
        unless guard.empty?
          # The guard alone decides: run after an inherited
          # require_authentication (`generate authentication`'s), it would
          # never see a visitor, who would be sent to sign in instead, which
          # tells them the page exists. A skip of a callback the application
          # does not have is a no-op. Controllers that declare the guard
          # themselves keep Rails' order: authentication first.
          out << "  # :#{guard} alone decides who sees the page: an application's\n"
          out << "  # require_authentication is skipped, so a visitor gets the guard's\n"
          out << "  # answer, not a redirect to sign in that shows the page exists.\n"
          out << "  skip_before_action :require_authentication\n"
          out << "  before_action :#{guard}\n"
          out << "\n"
          out << "  def run_callback(name)\n"
          out << "    case name\n"
          out << "    when :#{guard} then #{guard}\n"
          out << "    else super\n"
          out << "    end\n"
          out << "  end\n"
          out << "\n"
        end
        out << "  def index\n"
        out << "    render html: Cybertrain::JobsPage.page_html(self, #{path})\n"
        out << "  end\n"
        out << jobs_action_source("retry_all_action", "Cybertrain::JobsPage.retry_all_notice", path)
        out << jobs_action_source("discard_all_failed_action", "Cybertrain::JobsPage.discard_all_failed_notice", path)
        out << jobs_action_source("retry_action", "Cybertrain::JobsPage.retry_notice(params[:id])", path)
        out << jobs_action_source("discard_action", "Cybertrain::JobsPage.discard_notice(params[:id])", path)
        out << jobs_action_source("delete_action", "Cybertrain::JobsPage.delete_notice(params[:id])", path)
        out << "end\n"
        out
      end

      def self.jobs_action_source(method, notice, path)
        out = +""
        out << "\n"
        out << "  def #{method}\n"
        out << "    flash[:notice] = #{notice}\n"
        out << "    redirect_to #{path}, status: :see_other\n"
        out << "  end\n"
        out
      end

      # The line `spin run gen` prints for a jobs page without
      # before_action:; "" when it has one or none is drawn.
      def self.jobs_page_warning(page)
        path = page.jobs_path
        return "" if path.empty? || !page.jobs_before_action.empty?

        "warning: jobs_page #{path.inspect} has no before_action:, so anyone who can reach it can see, retry, discard and delete jobs " \
          "(add one: jobs_page #{path.inspect}, before_action: :require_admin)"
      end

      # A namespaced controller (Admin::UsersController) is written inside
      # `module Admin`, because gen/controllers.rb loads before any app file
      # could define the module. Its superclass, as ControllerScan resolved
      # it (a compact `class Admin::UsersController < ApplicationController`
      # line names the top-level class, and so does a bare name inside
      # `module Admin` unless gen found an Admin:: class of that name), is
      # written from the top level (`::ApplicationController`) to keep that
      # meaning inside the modules.
      # helpers: helper_methods_source's text, written last in the class.
      def self.class_source(info, ivars, callbacks = info.callbacks, helpers = "")
        parts = info.class_name.split("::")
        return plain_class_source(info.class_name, info.superclass_name, callbacks, ivars, helpers) if parts.size < 2

        superclass = info.superclass_name
        superclass = "::#{superclass}" unless superclass.start_with?("::")
        wrap_in_modules(info.class_name, plain_class_source(parts.last.to_s, superclass, callbacks, ivars, helpers))
      end

      # The controller's controller_layout ("" when neither it nor the
      # concerns it brings in declare a layout): each declaration in turn,
      # a conditional one (`only:` / `except:`) behind its `if`, up to the
      # first that applies to every action (what follows it is never
      # reached), else `super`. `layout "x"` is "layouts/x", `layout false`
      # "", and `layout :m` m's value: a name, false for none, or nil for
      # the inherited layout.
      # controller_layout's parameter and the method form's locals: names
      # no application method has, so `layout :action` or `layout :chosen`
      # calls the method.
      LAYOUT_ACTION = "layout_action__"

      def self.layout_source(info, infos, concerns)
        decls = layout_decls(info, infos, concerns)
        return "" if decls.empty?

        out = +""
        out << "\n"
        out << "  def controller_layout(#{LAYOUT_ACTION})\n"
        always = false
        # One local per method declaration: layout_chosen__, layout_chosen2__, ...
        methods = 0
        decls.each do |d|
          next if always

          methods += 1 unless d.layout_method.empty?
          local = methods < 2 ? "layout_chosen__" : "layout_chosen#{methods}__"
          lines = layout_value_lines(d, local)
          if d.unconditional?
            lines.each { |line| out << "    #{line}\n" }
            always = true
          else
            out << "    if #{layout_condition(d)}\n"
            lines.each_with_index do |line, n|
              out << (n == lines.size - 1 ? "      return #{line}\n" : "      #{line}\n")
            end
            out << "    end\n"
          end
        end
        out << "    super\n" unless always
        out << "  end\n"
        out
      end

      # The class's `layout` lines and those of the `included` blocks of
      # the concerns it brings in (its ancestors' are reached through
      # `super`), each concern's at its `include` line, in line order.
      def self.layout_decls(info, infos, concerns)
        decls = Array.new(0) { LayoutDecl.new("", "", [], [], 0) }
        positions = Array.new(0) { 0 }
        info.layouts.each do |d|
          decls << d
          positions << d.layout_line
        end
        from = Array.new(0) { 0 }
        ConcernScan.own_concerns(info, infos, concerns, from).each_with_index do |c, n|
          at = info.include_lines[from[n]]
          c.concern_layouts.each do |d|
            # After the class's own lines above the include (and the
            # concerns already placed there), before those below it.
            k = 0
            k += 1 while k < positions.size && positions[k] <= at
            decls.insert(k, d)
            positions.insert(k, at)
          end
        end
        decls
      end

      # `action == "a" || action == "b"` for only:, `action != "a" && ...`
      # for except: (only: wins when a line has both, as in Rails).
      def self.layout_condition(decl)
        unless decl.layout_only.empty?
          return decl.layout_only.map { |a| "#{LAYOUT_ACTION} == #{HelpersEmitter.literal(a)}" }.join(" || ")
        end

        decl.layout_except.map { |a| "#{LAYOUT_ACTION} != #{HelpersEmitter.literal(a)}" }.join(" && ")
      end

      # The lines computing a declaration's layout, the value last. A
      # layout method's nil is the inherited layout (`super`), as in Rails.
      # A name already under `layouts/` keeps it (`layout "layouts/admin"`
      # is layouts/admin, Rails' `_normalize_layout`), through
      # Controller.layout_path for a method's value.
      def self.layout_value_lines(decl, local)
        lines = Array.new(0) { "" }
        if decl.layout_method.empty?
          name = decl.layout_name
          lines << (name.empty? ? "\"\"" : HelpersEmitter.literal(name.start_with?("layouts/") ? name : "layouts/#{name}"))
        else
          lines << "#{local} = #{decl.layout_method}"
          lines << "return super if #{local}.nil?"
          lines << "#{local} == false ? \"\" : Cybertrain::Controller.layout_path(#{local}.to_s)"
        end
        lines
      end

      # The receiver of the argument checks in a controller's helper arms.
      HELPER_CHECKS = "Cybertrain::Template::Helpers."

      # The controller's helper_method? and call_helper_method ("" when it
      # and the concerns it brings in declare no helper method), each name
      # checked first.
      def self.helper_methods_source(info, infos, concerns, helper_modules)
        names = helper_method_names(info, infos, concerns)
        return "" if names.empty?

        defs = Array.new(0) { HelperDef.new("", 0, [], [], [], [], "") }
        names.each do |name|
          check_helper_method(name, helper_modules)
          error = Array.new(0) { "" }
          # The arm checks and calls with the signature of the def this
          # class reaches. A subclass that overrides the method without its
          # own `helper_method` line keeps the declaring class's arm, so
          # the declaring class's signature, not the override's, is the one
          # checked (Ruby would call the override with whatever the template
          # passed): redeclare `helper_method` in the subclass to change it.
          found = helper_def(info, infos, concerns, name, error)
          if found.nil?
            msg = "helper_method :#{name} in #{info.class_name}: no def #{name} in the controller, its parents or its concerns"
            raise ArgumentError, msg
          end
          # A def whose parameters a template cannot fill (`*rest`, `...`)
          # is refused, as the same def in app/helpers is.
          unless error.empty? || error[0].empty?
            msg = "helper_method :#{name} in #{info.class_name}: #{error[0]}"
            raise ArgumentError, msg
          end
          # A template passes no block to a helper method: the call has none.
          defs << HelperDef.new(name, found.line, found.required, found.optional, found.keywords_required, found.keywords_optional, "")
        end
        out = +""
        out << "\n"
        out << "  def helper_method?(name)\n"
        out << "    case name\n"
        out << "    when #{names.map { |n| HelpersEmitter.literal(n) }.join(", ")} then true\n"
        out << "    else super\n"
        out << "    end\n"
        out << "  end\n"
        out << "\n"
        out << "  def call_helper_method(name, args, kwargs)\n"
        out << "    case name\n"
        defs.each { |d| out << HelpersEmitter.def_arm(d, HELPER_CHECKS) }
        out << "    else super\n"
        out << "    end\n"
        out << "  end\n"
        out
      end

      # The names of the class's `helper_method` lines, then those of the
      # `included` blocks of the concerns it brings in (its ancestors' are
      # reached through `super`), each once.
      def self.helper_method_names(info, infos, concerns)
        names = Array.new(0) { "" }
        info.helper_methods.each { |n| names << n unless names.include?(n) }
        ConcernScan.own_concerns(info, infos, concerns).each do |c|
          c.included_body.each do |line|
            next if line.strip.start_with?("#")

            ControllerScan.helper_method_names(line).each { |n| names << n unless names.include?(n) }
          end
        end
        names
      end

      # A helper method may not take a name that a template helper of the
      # framework, a route helper or an application helper answers.
      def self.check_helper_method(name, helper_modules)
        if HelperScan::RESERVED_HELPER_NAMES.include?(name) || name.end_with?("_path") || name.end_with?("_url")
          msg = "helper_method :#{name}: #{name} is a framework helper"
          raise ArgumentError, msg
        end
        helper_modules.each do |m|
          m.defs.each do |d|
            next unless d.name == name

            msg = "helper_method :#{name}: #{name} is defined in #{m.name}"
            raise ArgumentError, msg
          end
        end
        nil
      end

      # The `def name` a call on the controller reaches, as Ruby looks it
      # up: the class's own, then its concerns' (the last include first),
      # then the same for each scanned parent; nil when none has one.
      # error receives the found def's parse error ("" when it has none).
      def self.helper_def(info, infos, concerns, name, error = Array.new(0) { "" })
        seen = Array.new(0) { "" }
        current = info
        until current.nil? || seen.include?(current.class_name)
          seen << current.class_name
          current.defs.each_with_index do |d, k|
            next unless d.name == name

            error << current.def_errors[k]
            return d
          end
          ConcernScan.expand(current.includes, concerns).reverse.each do |c|
            c.concern_defs.each_with_index do |d, k|
              next unless d.name == name

              error << c.concern_def_errors[k]
              return d
            end
          end
          current = find(infos, current.superclass_name)
        end
        nil
      end

      # The controller's rate_limit_key and rate_limit_condition? ("" when
      # neither it nor the concerns it brings in has a `rate_limit` line
      # naming a by: method, or an if: / unless: one): a `case` over the
      # names, each arm calling the method (by:'s value as a String, the
      # condition's as a Boolean), then `super`, so a parent's limits keep
      # their methods. The with: names are run_callback arms (the scans add
      # them to the callbacks). A name with no `def` in the controller, its
      # scanned parents or its concerns is refused with its line.
      def self.rate_limit_source(info, infos, concerns)
        keys = Array.new(0) { "" }
        conditions = Array.new(0) { "" }
        rate_limit_refs_with_concerns(info, infos, concerns).each do |ref|
          name = ref.rate_limit_method
          if helper_def(info, infos, concerns, name).nil?
            msg = "#{ref.rate_limit_place}: rate_limit #{ref.rate_limit_option}: :#{name} in #{info.class_name}: " \
                  "no def #{name} in the controller, its parents or its concerns"
            raise ArgumentError, msg
          end
          case ref.rate_limit_option
          when "by" then keys << name unless keys.include?(name)
          when "if", "unless" then conditions << name unless conditions.include?(name)
          end
        end
        out = +""
        unless keys.empty?
          out << "\n"
          out << "  def rate_limit_key(name)\n"
          out << "    case name\n"
          keys.each { |n| out << "    when :#{n} then #{n}.to_s\n" }
          out << "    else super\n"
          out << "    end\n"
          out << "  end\n"
        end
        unless conditions.empty?
          out << "\n"
          out << "  def rate_limit_condition?(name)\n"
          out << "    case name\n"
          conditions.each { |n| out << "    when :#{n} then !!#{n}\n" }
          out << "    else super\n"
          out << "    end\n"
          out << "  end\n"
        end
        out
      end

      # The RateLimitRefs of the class's `rate_limit` lines, then those of
      # the `included` blocks of the concerns it brings in.
      def self.rate_limit_refs_with_concerns(info, infos, concerns)
        refs = Array.new(0) { RateLimitRef.new("", "", "") }
        info.rate_limit_refs.each { |r| refs << r }
        ConcernScan.own_concerns(info, infos, concerns).each do |c|
          c.concern_rate_limit_refs.each { |r| refs << r }
        end
        refs
      end

      # The class's callback names, then those of the concerns it brings in
      # (its ancestors' are reached through `super`).
      def self.callbacks_with_concerns(info, infos, concerns)
        names = Array.new(0) { "" }
        info.callbacks.each { |n| names << n }
        ConcernScan.own_concerns(info, infos, concerns).each do |c|
          c.concern_callbacks.each { |n| names << n unless names.include?(n) }
        end
        names
      end

      # `body` (the source of `class X` or `module X`, X the last part of
      # full_name) inside `module A` ... for the parts before it, indented.
      def self.wrap_in_modules(full_name, body)
        parts = full_name.split("::")
        out = +""
        depth = 0
        parts.each_with_index do |mod, i|
          next if i == parts.size - 1

          out << ("  " * depth) << "module #{mod}\n"
          depth += 1
        end
        body.each_line do |line|
          out << ("  " * depth) unless line == "\n"
          out << line
        end
        while depth > 0
          depth -= 1
          out << ("  " * depth) << "end\n"
        end
        out
      end

      def self.plain_class_source(class_name, superclass_name, callbacks, ivars, helpers = "")
        out = +""
        out << "class #{class_name} < #{superclass_name}\n"
        out << "  def view_assigns\n"
        out << "    #{hash_source(ivars)}\n"
        out << "  end\n"
        unless callbacks.empty?
          out << "\n"
          out << "  def run_callback(name)\n"
          out << "    case name\n"
          callbacks.each { |n| out << "    when :#{n} then #{n}\n" }
          out << "    else super\n"
          out << "    end\n"
          out << "  end\n"
        end
        out << helpers
        out << "end\n"
        out
      end

      # { "post" => @post, "posts" => @posts }
      def self.hash_source(ivars)
        return "{}" if ivars.empty?

        "{ " + ivars.map { |n| "\"#{n}\" => @#{n}" }.join(", ") + " }"
      end

      # The class's own ivars after those of its scanned ancestors, each
      # class's followed by those of the concerns it brings in.
      def self.visible_ivars(info, infos, concerns = Array.new(0) { ConcernInfo.new("", "", 0) })
        chain = []
        current = info
        until current.nil? || chain.include?(current.class_name)
          chain.unshift(current.class_name)
          current = find(infos, current.superclass_name)
        end
        names = []
        chain.each do |class_name|
          klass = find(infos, class_name)
          klass.ivars.each { |n| names << n unless names.include?(n) }
          ConcernScan.own_concerns(klass, infos, concerns).each do |c|
            c.concern_ivars.each { |n| names << n unless names.include?(n) }
          end
        end
        names
      end

      def self.find(infos, class_name)
        infos.each { |i| return i if i.class_name == class_name }
        nil
      end

      # Keeps file order but moves each class after its superclass, so the
      # file is loadable top to bottom (CRuby needs the superclass defined).
      def self.parents_first(infos)
        pending = infos.dup
        ordered = []
        until pending.empty?
          ready = pending.select { |i| find(pending, i.superclass_name).nil? }
          ready = pending.dup if ready.empty?   # a cycle: give up on ordering
          ready.each do |i|
            ordered << i
            pending.delete(i)
          end
        end
        ordered
      end
    end
  end
end

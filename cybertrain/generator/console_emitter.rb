module Cybertrain
  module Gen
    # Writes gen/console.rb (spec 7): the tables `./app console` reaches the
    # generated models through, since a console line names a model by a
    # String and Spinel has no `const_get` (spikes/NOTES.md rule 1).
    # Gen::Console.scope / records / create are `case`s over the model
    # names; the file then installs them as Cybertrain::Console's four
    # builders (cybertrain/console.rb defines them with raising defaults).
    module ConsoleEmitter
      HEADER = "# Generated by `spin run gen` from db/schema.rb. Do not edit.\n"

      # models: the model class names ("Article"), sorted.
      def self.emit(models)
        out = +""
        out << HEADER
        out << "require \"cybertrain/console\"\n"
        out << "\n"
        out << "module Gen\n"
        out << "  module Console\n"
        if models.empty?
          out << "    MODEL_NAMES = Array.new(0) { \"\" }\n"
        else
          out << "    MODEL_NAMES = [#{models.map { |m| "\"#{m}\"" }.join(", ")}]\n"
        end
        out << "\n"
        out << "    # Article -> Article.all, as a Cybertrain::Relation.\n"
        out << "    def self.scope(name)\n"
        out << name_case(models, "\#{m}.all", "Cybertrain::Console.unknown_model(name)")
        out << "    end\n"
        out << "\n"
        out << "    # The records of a relation scope returned, as Array<Cybertrain::Model>.\n"
        out << "    def self.records(relation)\n"
        out << "      out = Array.new(0) { Cybertrain::Model.new }\n"
        unless models.empty?
          out << "      case relation\n"
          models.each do |m|
            out << "      when #{m}Relation then relation.to_a.each { |r| out << r }\n"
          end
          out << "      end\n"
        end
        out << "      out\n"
        out << "    end\n"
        out << "\n"
        out << "    # Article.create(attrs); attrs: Hash<Symbol, polymorphic>.\n"
        out << "    def self.create(name, attrs)\n"
        out << name_case(models, "\#{m}.create(attrs)", "Cybertrain::Console.unknown_record(name)")
        out << "    end\n"
        out << "  end\n"
        out << "end\n"
        out << "\n"
        out << "Cybertrain::Console.scope_builder = ->(name) { Gen::Console.scope(name) }\n"
        out << "Cybertrain::Console.records_builder = ->(relation) { Gen::Console.records(relation) }\n"
        out << "Cybertrain::Console.create_builder = ->(name, attrs) { Gen::Console.create(name, attrs) }\n"
        out << "Cybertrain::Console.model_names = Gen::Console::MODEL_NAMES\n"
        out
      end

      # `case name when "Article" then <expr>` with expr's "#{m}" replaced
      # by the model; an unknown name goes to `unknown`, one of
      # Cybertrain::Console's raising helpers, which raises UnknownModel
      # listing the models and is typed as returning what the arm returns
      # (a Relation for scope, a Model for create), so an app with no
      # tables still compiles (NOTES rule 79).
      def self.name_case(models, template, unknown)
        out = +""
        if models.empty?
          out << "      #{unknown}\n"
          return out
        end
        out << "      case name\n"
        models.each do |m|
          expr = template.gsub("\#{m}", m)
          out << "      when \"#{m}\" then #{expr}\n"
        end
        out << "      else #{unknown}\n"
        out << "      end\n"
        out
      end
    end
  end
end

require "cybertrain/generator/job_scan"

module Cybertrain
  module Gen
    # Writes gen/jobs.rb (spec sections 2.2 and 3): per job class the
    # reopened class with `self.job_kind`, `perform_later`, `perform_at`,
    # `perform_in`, `perform_now` and `self.run_job(run)`, whose policies are
    # literal `rescue` arms in declaration order (Spinel has no computed
    # send, so the policy table is code); then one `Cybertrain::Job.register`
    # per class, whose block calls the concrete class's run_job (never
    # through Job::Base: spikes/NOTES.md rule 88). A job inherits its
    # ancestors' policies (JobScan.ancestors: the class's own arms first,
    # then each ancestor's outward) and, when it declares no
    # `limits_concurrency`, the nearest ancestor's. ApplicationJob is not a
    # job: nothing is written for it. Every exception constant of an arm is
    # written from the top level (`rescue ::ArgumentError`), so the reopened
    # class's own constants and modules cannot re-resolve it (rule 89).
    module JobsEmitter
      HEADER = "# Generated by `spin run gen` from app/jobs. Do not edit.\n"

      def self.emit(infos)
        out = +""
        out << HEADER
        jobs = Array.new(0) { JobScan.empty_info }
        infos.each { |info| jobs << info unless info.class_name == "ApplicationJob" }
        return out if jobs.empty?

        jobs.each do |info|
          out << "\n"
          out << class_source(info, policies_of(info, infos))
        end
        out << "\n"
        jobs.each { |info| out << register_line(info, infos) }
        out
      end

      # A job's own policies, then each ancestor's, nearest first.
      def self.policies_of(info, infos)
        out = Array.new(0) { PolicyInfo.new("", "", 0, false, 0, 0) }
        info.policies.each { |p| out << p }
        JobScan.ancestors(info, infos).each { |a| a.policies.each { |p| out << p } }
        out
      end

      # The most attempts any retry policy allows; 0 without one (the
      # default policy's Config#job_max_attempts).
      def self.max_attempts(policies)
        max = 0
        policies.each { |p| max = p.attempts if p.policy_kind == "retry" && p.attempts > max }
        max
      end

      def self.register_line(info, infos)
        to = info.concurrency_to
        key = info.concurrency_key
        JobScan.ancestors(info, infos).each do |a|
          break if to > 0

          to = a.concurrency_to
          key = a.concurrency_key
        end
        max = max_attempts(policies_of(info, infos))
        "Cybertrain::Job.register(#{info.class_name.inspect}, concurrency: #{to}, concurrency_key: #{key.inspect}, " \
          "max_attempts: #{max}) { |run| #{info.class_name}.run_job(run) }\n"
      end

      # A namespaced job is written inside its enclosing modules and classes
      # (JobInfo#scope_keywords), with its superclass spelled from the top
      # level (as ComponentsEmitter does).
      def self.class_source(info, policies)
        parts = info.class_name.split("::")
        return plain_class_source(info, info.class_name, info.superclass_name, policies) if parts.size < 2

        superclass = info.superclass_name
        superclass = "::#{superclass}" unless superclass.start_with?("::")
        body = plain_class_source(info, parts.last.to_s, superclass, policies)
        out = +""
        depth = 0
        parts.each_with_index do |mod, i|
          next if i == parts.size - 1

          out << ("  " * depth) << "#{info.scope_keywords[i]} #{mod}\n"
          depth += 1
        end
        body.each_line do |line|
          out << ("  " * depth) unless line == "\n"
          out << line
        end
        while depth > 0
          depth -= 1
          out << ("  " * depth) << "end\n"
        end
        out
      end

      def self.plain_class_source(info, name, superclass, policies)
        full = info.class_name
        out = +""
        out << "class #{name} < #{superclass}\n"
        out << "  def self.job_kind\n"
        out << "    #{full.inspect}\n"
        out << "  end\n"
        out << "\n"
        out << "  def self.perform_later(args = {})\n"
        out << hash_check(full, "perform_later")
        out << "    Cybertrain::Job.enqueue(job_kind, JSON.generate(args))\n"
        out << "  end\n"
        out << "\n"
        out << "  def self.perform_at(time, args = {})\n"
        out << hash_check(full, "perform_at")
        out << "    Cybertrain::Job.enqueue(job_kind, JSON.generate(args), run_at: time)\n"
        out << "  end\n"
        out << "\n"
        out << "  def self.perform_in(seconds, args = {})\n"
        out << hash_check(full, "perform_in")
        out << "    Cybertrain::Job.enqueue(job_kind, JSON.generate(args), run_at: Time.current + seconds)\n"
        out << "  end\n"
        out << "\n"
        out << "  def self.perform_now(args = {})\n"
        out << hash_check(full, "perform_now")
        out << "    new.perform(Cybertrain::Cast.hash(args))\n"
        out << "    nil\n"
        out << "  end\n"
        out << "\n"
        out << run_job_source(policies)
        out << "end\n"
        out
      end

      # The ArgumentError for args that are not a Hash, its message in a
      # local first (NOTES rule 58).
      def self.hash_check(full, method)
        out = +""
        out << "    unless args.is_a?(Hash)\n"
        out << "      message = \"#{full}.#{method}: args must be a Hash (a JSON object), not \#{args.class.name}\"\n"
        out << "      raise ArgumentError, message\n"
        out << "    end\n"
        out
      end

      # run_job(run): perform with the parsed args, each policy a rescue
      # arm in declaration order (the first that matches wins). A retry arm
      # runs retries_exhausted only once Job.retry_later wrote `failed`; a
      # discard arm never runs it.
      def self.run_job_source(policies)
        out = +""
        out << "  def self.run_job(run)\n"
        out << "    job = new\n"
        if policies.empty?
          out << "    job.perform(run.run_args)\n"
        else
          out << "    begin\n"
          out << "      job.perform(run.run_args)\n"
          policies.each do |p|
            out << "    rescue ::#{p.exception_class} => e\n"
            if p.policy_kind == "retry"
              out << "      if Cybertrain::Job.retry_later(run, e, #{p.wait_base}, #{p.polynomial}, #{p.attempts}) == Cybertrain::Job::OUTCOME_FAILED\n"
              out << "        job.retries_exhausted(e)\n"
              out << "      end\n"
            else
              out << "      Cybertrain::Job.discard(run, e)\n"
            end
          end
          out << "    end\n"
        end
        out << "    nil\n"
        out << "  end\n"
        out
      end
    end
  end
end

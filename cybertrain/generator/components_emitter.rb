require "cybertrain/generator/component_scan"

module Cybertrain
  module Gen
    # Writes gen/components.rb (spec 3.2): per component class its
    # view_assigns, call_view_method / view_method? case tables,
    # component_name and component_template, then Gen::Components.build,
    # the `case` from a template's component name to the class's `new`
    # (one arm per subset of the optional keywords given, as gen/helpers.rb
    # does for helpers), installed as Views.component_builder.
    module ComponentsEmitter
      HEADER = "# Generated by `spin run gen` from app/components. Do not edit.\n"

      def self.emit(infos)
        out = +""
        out << HEADER
        infos.each do |info|
          out << "\n"
          out << class_source(info)
        end
        out << "\n"
        out << "module Gen\n"
        out << "  module Components\n"
        out << "    # kwargs: Hash<String, polymorphic> from the template.\n"
        out << "    def self.build(name, kwargs)\n"
        unless infos.empty?
          out << "      case name\n"
          infos.each { |info| out << build_arm(info) }
          out << "      else\n"
          out << "  " << unknown_raise << "\n"
          out << "      end\n"
        else
          out << unknown_raise << "\n"
        end
        out << "    end\n"
        out << "  end\n"
        out << "end\n"
        out << "\n"
        out << "Cybertrain::Views.component_builder = ->(name, kwargs) { Gen::Components.build(name, kwargs) }\n"
        out
      end

      def self.unknown_raise
        "      raise Cybertrain::Component::Unknown, \"no component '\#{name}' (app/components/\#{name}_component.rb, then `spin run gen`)\""
      end

      # A namespaced component is written inside its modules, with its
      # superclass spelled from the top level (as ControllersEmitter does).
      def self.class_source(info)
        parts = info.class_name.split("::")
        return plain_class_source(info, info.class_name, info.superclass_name) if parts.size < 2

        superclass = info.superclass_name
        superclass = "::#{superclass}" unless superclass.start_with?("::")
        body = plain_class_source(info, parts.last.to_s, superclass)
        out = +""
        depth = 0
        parts.each_with_index do |mod, i|
          next if i == parts.size - 1

          out << ("  " * depth) << "module #{mod}\n"
          depth += 1
        end
        body.each_line do |line|
          out << ("  " * depth) unless line == "\n"
          out << line
        end
        while depth > 0
          depth -= 1
          out << ("  " * depth) << "end\n"
        end
        out
      end

      def self.plain_class_source(info, class_name, superclass_name)
        out = +""
        out << "class #{class_name} < #{superclass_name}\n"
        out << "  def view_assigns\n"
        out << "    #{assigns_source(info)}\n"
        out << "  end\n"
        out << "\n"
        out << "  def call_view_method(name)\n"
        if info.view_methods.empty?
          out << "    nil\n"
        else
          out << "    case name\n"
          info.view_methods.each { |m| out << "    when :#{m} then #{m}\n" }
          out << "    else nil\n"
          out << "    end\n"
        end
        out << "  end\n"
        out << "\n"
        out << "  def view_method?(name)\n"
        if info.view_methods.empty?
          out << "    false\n"
        else
          out << "    case name\n"
          out << "    when #{info.view_methods.map { |m| "\"#{m}\"" }.join(", ")} then true\n"
          out << "    else false\n"
          out << "    end\n"
        end
        out << "  end\n"
        out << "\n"
        out << "  def component_name\n"
        out << "    \"#{info.component_name}\"\n"
        out << "  end\n"
        out << "\n"
        out << "  def component_template\n"
        out << "    \"#{info.template}\"\n"
        out << "  end\n"
        out << "end\n"
        out
      end

      # The ivars a template reads as locals, without those a view method
      # of the same name answers (the method wins, as in ViewComponent):
      # a typed Hash of polymorphic values even when there are none.
      def self.assigns_source(info)
        names = Array.new(0) { "" }
        info.ivars.each { |n| names << n unless info.view_methods.include?(n) || n == "content" }
        return "super" if names.empty?

        "{ " + names.map { |n| "\"#{n}\" => @#{n}" }.join(", ") + " }"
      end

      def self.build_arm(info)
        out = +""
        name = info.component_name
        known = info.keywords_required + info.keywords_optional
        known_source = known.empty? ? "Array.new(0) { \"\" }" : "[#{known.map { |k| "\"#{k}\"" }.join(", ")}]"
        out << "      when \"#{name}\"\n"
        out << "        Cybertrain::Component.check_keywords!(name, kwargs, #{known_source}, #{info.keywords_required.size})\n"
        q = info.keywords_optional.size
        if q == 0
          out << "        #{new_source(info, Array.new(0) { "" })}\n"
          return out
        end
        last = (1 << q) - 1
        last.downto(0) do |mask|
          keys = Array.new(0) { "" }
          info.keywords_optional.each_with_index do |k, i|
            keys << k if mask & (1 << (q - 1 - i)) != 0
          end
          cond = keys.map { |k| "kwargs.key?(\"#{k}\")" }.join(" && ")
          if mask == last
            out << "        if #{cond} then #{new_source(info, keys)}\n"
          elsif mask == 0
            out << "        else #{new_source(info, keys)}\n"
          else
            out << "        elsif #{cond} then #{new_source(info, keys)}\n"
          end
        end
        out << "        end\n"
        out
      end

      def self.new_source(info, keys)
        args = Array.new(0) { "" }
        info.keywords_required.each { |k| args << "#{k}: kwargs[\"#{k}\"]" }
        keys.each { |k| args << "#{k}: kwargs[\"#{k}\"]" }
        klass = "::#{info.class_name}"
        args.empty? ? "#{klass}.new" : "#{klass}.new(#{args.join(", ")})"
      end
    end
  end
end

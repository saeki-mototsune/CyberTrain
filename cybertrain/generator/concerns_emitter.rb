require "cybertrain/generator/source_text"
require "cybertrain/generator/concern_scan"
require "cybertrain/generator/controllers_emitter"
require "cybertrain/generator/model_scan"

module Cybertrain
  module Gen
    # Writes gen/concerns.rb (docs/design.md D60), which
    # gen/app.rb requires last, once every application class is defined:
    #
    # - per concern with `class_methods do ... end`, the module reopened
    #   with each of those methods as `def self.x`;
    # - per controller that includes concerns its scanned ancestors do not,
    #   the class reopened (inside its modules when namespaced) with a
    #   forwarder `def self.x(...) = Concern.x(...)` per class method, then
    #   each concern's `included do ... end` body, as written, between
    #   `concern_insert_at(callbacks_index, rescues_index)` and
    #   `concern_insert_done`, so its declarations take the place of the
    #   `include` line among the class's own.
    #
    # A concern brought in again by an ancestor's include is left out (its
    # callbacks would run twice). A `class_methods` method may share its
    # name with an instance method: the forwarder is a class method, and
    # the blanked copy defines no instance method for it.
    #
    # Models get the same: per model that
    # includes concerns, the forwarders and each concern's `included` body
    # between `model_concern_insert_at(validators_index)` and
    # `model_concern_insert_done` (emit_models).
    #
    # The concerns themselves are loaded from gen/concerns/<path under
    # app/> (module_files): each concern's file with its `included do` and
    # `class_methods do` blocks blanked, line for line. Spinel compiles a
    # block that never runs against the module around it
    # (spikes/NOTES.md rule 92), so `-> { where(hidden: 0) }` in an
    # `included` block would not build; spliced into the class, it does.
    module ConcernsEmitter
      HEADER = "# Generated by `spin run gen` from app/controllers and app/models. Do not edit.\n" \
               "#\n" \
               "# Each concern's `class_methods do ... end` as methods of the concern, and\n" \
               "# in every class that includes it a forwarder per method and the\n" \
               "# concern's `included do ... end` body, at the position of the `include`\n" \
               "# (Cybertrain::Controller.concern_insert_at,\n" \
               "# Cybertrain::Model.model_concern_insert_at). Loaded after the\n" \
               "# application's classes.\n"

      def self.emit(controller_infos, concern_infos, model_infos = Array.new(0) { ModelInfo.empty("", "", Array.new(0) { "" }) },
                    model_concern_infos = ConcernScan.no_concern_infos)
        out = +""
        out << HEADER
        out << class_methods_modules(concern_infos)
        out << class_methods_modules(model_concern_infos)
        ControllersEmitter.parents_first(controller_infos).each do |info|
          from = Array.new(0) { 0 }
          own = ConcernScan.own_concerns(info, controller_infos, concern_infos, from)
          next if own.empty?

          body = class_body(info, own, from)
          next if body.empty?

          out << "\n"
          out << reopened_class(info.class_name, body)
        end
        out << emit_models(model_infos, model_concern_infos)
        out
      end

      # The module holding each concern's class methods, for the concerns
      # that have any.
      def self.class_methods_modules(concerns)
        out = +""
        concerns.each do |c|
          next if c.class_method_names.empty?

          out << "\n"
          out << SourceText.wrap_in_scopes(c.concern_name, Array.new(0) { "" }, class_methods_source(c))
        end
        out
      end

      # `class X` reopened around body, inside X's modules.
      def self.reopened_class(class_name, body)
        last = class_name.split("::").last.to_s
        source = +"class #{last}\n"
        body.each_line { |line| source << (line == "\n" ? line : "  #{line}") }
        source << "end\n"
        SourceText.wrap_in_scopes(class_name, Array.new(0) { "" }, source)
      end

      # The reopening of every model that includes concerns: a forwarder
      # per class method of its concerns, then each concern's `included`
      # body between `model_concern_insert_at(n)` (n: the model's own
      # `validates` calls above the `include`) and
      # `model_concern_insert_done`. A class_methods name that is a
      # scope's or a model class method's is refused
      # (check_model_class_method).
      def self.emit_models(model_infos, concern_infos)
        out = +""
        model_infos.each do |info|
          next if info.concern_names.empty?

          own = ConcernScan.no_concern_infos
          info.concern_names.each do |name|
            c = ConcernScan.find(concern_infos, name)
            own << c unless c.nil?
          end
          body = +""
          own.each do |c|
            c.class_method_names.each_with_index do |m, k|
              check_model_class_method(info, c, m, c.class_method_line_numbers[k])
              body << "def self.#{m}(...) = #{c.concern_name}.#{m}(...)\n"
            end
          end
          spliced = +""
          where = ControllerScan.app_path(info.file)
          own.each_with_index do |c, n|
            next if c.included_body.empty?

            k = info.concern_from[n]
            spliced << "# #{c.concern_name} (include #{info.includes[k]} at #{where}:#{info.include_lines[k]})\n"
            spliced << "model_concern_insert_at(#{info.include_validates[k]})\n"
            dedent(c.included_body).each { |line| spliced << line }
            spliced << "model_concern_insert_done\n"
          end
          body << "\n" unless body.empty? || spliced.empty?
          body << spliced
          next if body.empty?

          out << "\n"
          out << reopened_class(info.class_name, body)
        end
        out
      end

      # A model concern's class_methods name m (written at line) must not
      # be a scope's name (gen/models defines `def self.<scope>` on the
      # model, which the forwarder would redefine) or a class method every
      # model and Relation already has (ModelScan::RESERVED_SCOPE_NAMES:
      # `where`, `all`, ...). Each refusal names both places.
      def self.check_model_class_method(info, concern, m, line)
        place = "#{ControllerScan.app_path(concern.concern_file)}:#{line}: class_methods def #{m}: "
        info.scopes.each do |sc|
          next unless sc.name == m

          msg = "#{place}#{info.class_name}, which includes #{concern.concern_name}, has scope :#{m} " \
                "(#{ControllerScan.app_path(sc.file)}:#{sc.line}), and both would define #{info.class_name}.#{m}; rename one"
          raise ArgumentError, msg
        end
        if ModelScan::RESERVED_SCOPE_NAMES.include?(m)
          msg = "#{place}every model and Relation already has #{m} (Cybertrain::Model, Cybertrain::Relation); " \
                "a forwarder would replace it in #{info.class_name}, so rename it"
          raise ArgumentError, msg
        end
        nil
      end

      # gen/concerns/<path under app/> => the concern's file with its
      # `included do` and `class_methods do` blocks blank (each line
      # becomes an empty one, so line numbers match the file), then a
      # comment naming it as generated.
      def self.module_files(concern_infos)
        out = { "" => "" }
        out.delete("")
        concern_infos.each do |c|
          path = ControllerScan.app_path(c.concern_file)
          out["gen/concerns/#{path.delete_prefix("app/")}"] = module_source(c, File.read(c.concern_file))
        end
        out
      end

      def self.module_source(concern, source)
        out = +""
        n = 0
        source.each_line do |raw|
          n += 1
          blank = false
          concern.block_starts.each_with_index { |start, k| blank = true if n >= start && n <= concern.block_ends[k] }
          out << (blank ? "\n" : raw)
        end
        out << "\n" unless out.empty? || out.end_with?("\n")
        out << "\n# Generated by `spin run gen` from #{ControllerScan.app_path(concern.concern_file)}. Do not edit.\n"
        out
      end

      # `module AdminGate` with the class methods as `def self.x`.
      def self.class_methods_source(concern)
        last = concern.concern_name.split("::").last.to_s
        out = +"module #{last}\n"
        lines = dedent(concern.class_method_lines)
        lines.each do |line|
          if line.start_with?("def ") && !line.start_with?("def self.")
            out << "  def self.#{line[4, line.size - 4]}"
          elsif line == "\n"
            out << line
          else
            out << "  #{line}"
          end
        end
        out << "end\n"
        out
      end

      def self.class_body(info, own, from)
        out = +""
        own.each do |c|
          c.class_method_names.each { |m| out << "def self.#{m}(...) = #{c.concern_name}.#{m}(...)\n" }
        end
        spliced = +""
        added_callbacks = 0
        added_rescues = 0
        where = ControllerScan.app_path(info.file)
        own.each_with_index do |c, n|
          next if c.included_body.empty?

          k = from[n]
          spliced << "# #{c.concern_name} (include #{info.includes[k]} at #{where}:#{info.include_lines[k]})\n"
          spliced << "concern_insert_at(#{info.include_positions[k] + added_callbacks}, #{info.rescue_positions[k] + added_rescues})\n"
          dedent(c.included_body).each { |line| spliced << line }
          spliced << "concern_insert_done\n"
          added_callbacks += c.callback_count
          added_rescues += c.rescue_count
        end
        out << "\n" unless out.empty? || spliced.empty?
        out << spliced
        out
      end

      # The lines without their common indentation, blank lines as "\n",
      # leading and trailing blank lines dropped.
      def self.dedent(lines)
        min = -1
        lines.each do |line|
          next if line.strip == ""

          n = SourceText.indent_of(line)
          min = n if min < 0 || n < min
        end
        out = Array.new(0) { "" }
        lines.each do |line|
          if line.strip == ""
            out << "\n" unless out.empty?
          else
            text = line[min, line.size - min].to_s
            text += "\n" unless text.end_with?("\n")
            out << text
          end
        end
        out.pop while !out.empty? && out.last == "\n"
        out
      end
    end
  end
end

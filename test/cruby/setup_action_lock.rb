require "cybertrain/test"
require "tmpdir"
require "yaml"
require "open3"

# The step of .github/actions/setup-cybertrain/action.yml that reads the
# framework commit out of an application's spin.lock, run as the action
# runs it (bash, LOCKFILE, GITHUB_OUTPUT) on each form spin writes: a git
# dependency, an index version (`cybertrain = "X.Y.Z"`, which locks in the
# same shape, with the repository the index names) and a path dependency.
# The lock texts are what spin of the pinned Spinel release wrote for each
# form (the index one against a local index, SPIN_INDEX=file://...).
# Not preview code: it is here because script/test-cruby is where a test
# that Spinel cannot compile (YAML, a subprocess) runs.

ACTION = ".github/actions/setup-cybertrain/action.yml"
LOCK_STEP = YAML.load_file(ACTION).fetch("runs").fetch("steps").find { |step| step["id"] == "lock" }.fetch("run")

HEADER = "# generated by spin lock -- diff me, don't edit me\n\n"
SHA = "d35fdc0147c349211c22602233146c58741e2799"

# The step's exit status, what it wrote to GITHUB_OUTPUT and its stderr.
def read_lock(text)
  Dir.mktmpdir("setup-action-lock") do |dir|
    File.write(File.join(dir, "spin.lock"), text)
    File.write(File.join(dir, "output"), "")
    env = { "LOCKFILE" => "spin.lock", "GITHUB_OUTPUT" => File.join(dir, "output") }
    _, err, status = Open3.capture3(env, "bash", "-c", LOCK_STEP, chdir: dir)
    [status.exitstatus, File.read(File.join(dir, "output")), err]
  end
end

test "a git dependency's lock gives the repository and the commit" do
  lock = HEADER + "[lock.cybertrain]\nversion = \"0.4.1\"\ngit = \"https://github.com/saeki-mototsune/cybertrain\"\nref = \"#{SHA}\"\n"
  assert_equal [0, "git=https://github.com/saeki-mototsune/cybertrain\nref=#{SHA}\n", ""], read_lock(lock)
end

test "an index version locks in the same shape and reads the same" do
  # spin.toml: cybertrain = "0.4.1"; `git` is the index entry's `repo`.
  lock = HEADER + "[lock.cybertrain]\nversion = \"0.4.1\"\ngit = \"https://github.com/saeki-mototsune/CyberTrain\"\nref = \"#{SHA}\"\n"
  assert_equal [0, "git=https://github.com/saeki-mototsune/CyberTrain\nref=#{SHA}\n", ""], read_lock(lock)
end

test "another package's table is not the framework's" do
  lock = HEADER + "[lock.cybertrain]\nversion = \"0.4.1\"\ngit = \"https://example.com/cybertrain\"\nref = \"#{SHA}\"\n\n" \
                  "[lock.pg]\nversion = \"0.1.0\"\ngit = \"https://github.com/rubys/spinel-pg\"\nref = \"ca485ffcad655f6d2c198e9ace5e3171fedecfa6\"\n"
  assert_equal [0, "git=https://example.com/cybertrain\nref=#{SHA}\n", ""], read_lock(lock)
end

test "a path dependency has no commit: the step fails and names framework-path" do
  status, output, err = read_lock(HEADER + "[lock.cybertrain]\nversion = \"0.4.1\"\npath = \"/src/cybertrain\"\n")
  assert_equal 1, status
  assert_equal "", output
  assert_equal "setup-cybertrain: spin.lock locks a path dependency (/src/cybertrain); " \
               "commit a spin.lock for a git or an index dependency, or pass framework-path\n", err
end

test "a lock without the framework, or with a ref that is not a commit, fails" do
  status, output, err = read_lock(HEADER)
  assert_equal [1, ""], [status, output]
  assert_includes err, "locks no cybertrain commit"
  status, output, = read_lock(HEADER + "[lock.cybertrain]\nversion = \"0.4.1\"\ngit = \"https://example.com/cybertrain\"\nref = \"v0.4.1\"\n")
  assert_equal [1, ""], [status, output]
end

Cybertrain::Test.run!

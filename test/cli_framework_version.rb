require "tmpdir"
require "cybertrain/test"
require "cybertrain/cli"
require_relative "support/file_tree"

# The command refuses an application on another release of the framework
# (docs/design.md D89): what FrameworkVersion reads from spin.lock and
# spin.toml, and that the CLI's application commands stop on it before the
# toolchain or spin is touched. No spin, no network. CRuby-portable.
ROOT = Dir.mktmpdir("cybertrain-cli-framework-version")
Dir.chdir(ROOT)

at_exit do
  Dir.chdir("/")
  FileTree.remove(ROOT)
end

GIT = "https://github.com/saeki-mototsune/cybertrain".freeze
SHA = "0123456789abcdef0123456789abcdef01234567".freeze
FrameworkVersion = Cybertrain::CLI::FrameworkVersion

# An application in the current directory: spin.toml with `dependency` as
# the value of `cybertrain =` ("" for no dependency), and spin.lock holding
# `lock` (none when "").
def app(dependency, lock)
  toml = "[package]\nname = \"blog\"\nversion = \"0.1.0\"\n\n[dependencies]\n"
  toml += "redis = \"0.1.0\"\ncybertrain = #{dependency}\n" unless dependency == ""
  File.write("spin.toml", toml)
  File.delete("spin.lock") if File.exist?("spin.lock")
  File.write("spin.lock", "# generated by spin lock -- diff me, don't edit me\n\n#{lock}") unless lock == ""
end

def git_dep(ref)
  "{ git = \"#{GIT}\", ref = \"#{ref}\" }"
end

# A [lock.cybertrain] table as spin writes it for a git or index
# dependency, after another package's table.
def git_lock(version)
  "[lock.redis]\nversion = \"9.9.9\"\ngit = \"https://example.com/redis\"\nref = \"#{SHA}\"\n\n" \
    "[lock.cybertrain]\nversion = \"#{version}\"\ngit = \"#{GIT}\"\nref = \"#{SHA}\"\n"
end

def path_lock(version)
  "[lock.cybertrain]\nversion = \"#{version}\"\npath = \"/src/cybertrain\"\n"
end

test "the locked version equal to the command's is no problem" do
  app(git_dep("v1.2.3"), git_lock("1.2.3"))
  assert_equal "", FrameworkVersion.problem(".", "1.2.3")
  app("\"1.2.3\"", git_lock("1.2.3"))
  assert_equal "", FrameworkVersion.problem(".", "1.2.3")
end

test "another locked version is refused, with both versions and both ways out" do
  app(git_dep("v1.3.0"), git_lock("1.3.0"))
  puts FrameworkVersion.problem(".", "1.2.3")
  assert_includes FrameworkVersion.problem(".", "1.2.3"), "cybertrain 1.3.0 (spin.lock)"
  assert_includes FrameworkVersion.problem(".", "1.2.3"), "command is 1.2.3"
  assert_includes FrameworkVersion.problem(".", "1.2.3"), "gem install cybertrain -v 1.3.0"
  assert_includes FrameworkVersion.problem(".", "1.2.3"), "ref = \"v1.2.3\""
  # `spin lock` keeps a locked git commit, so the way out removes the lock.
  assert_includes FrameworkVersion.problem(".", "1.2.3"), "rm spin.lock && cybertrain spin lock"
end

test "a git dependency: spin.lock decides while spin.toml is ahead of it, spin builds the locked commit" do
  app(git_dep("v1.3.0"), git_lock("1.2.3"))
  assert_equal "", FrameworkVersion.problem(".", "1.2.3")
  assert_includes FrameworkVersion.problem(".", "1.3.0"), "cybertrain 1.2.3 (spin.lock)"
end

test "an index dependency: the lock decides only while spin.toml's constraint allows it" do
  app("\"~> 1.2\"", git_lock("1.2.9"))
  assert_equal "", FrameworkVersion.problem(".", "1.2.9")
  assert_includes FrameworkVersion.problem(".", "1.2.3"), "cybertrain 1.2.9 (spin.lock)"
  app("\">= 1.2\"", git_lock("1.3.0"))
  assert_includes FrameworkVersion.problem(".", "1.2.3"), "cybertrain 1.3.0 (spin.lock)"
  app("\"*\"", git_lock("1.3.0"))
  assert_includes FrameworkVersion.problem(".", "1.2.3"), "cybertrain 1.3.0 (spin.lock)"
  app("{ version = \"~> 1.2.0\", features = [\"a\"] }", git_lock("1.2.9"))
  assert_includes FrameworkVersion.problem(".", "1.2.3"), "cybertrain 1.2.9 (spin.lock)"
end

test "an index dependency moved to another exact version, not relocked: spin.toml decides, as spin reselects" do
  app("\"1.3.0\"", git_lock("1.2.3"))
  puts FrameworkVersion.problem(".", "1.2.3")
  assert_includes FrameworkVersion.problem(".", "1.2.3"), "cybertrain 1.3.0 (spin.toml)"
  assert_includes FrameworkVersion.problem(".", "1.2.3"), "cybertrain = \"1.2.3\""
  refute FrameworkVersion.problem(".", "1.2.3").include?("rm spin.lock")
  assert_equal "", FrameworkVersion.problem(".", "1.3.0")
  app("{ version = \"1.3.0\" }", git_lock("1.2.3"))
  assert_includes FrameworkVersion.problem(".", "1.2.3"), "cybertrain 1.3.0 (spin.toml)"
end

test "an index dependency whose range no longer allows the lock is refused until relocked" do
  app("\"~> 1.3\"", git_lock("1.2.3"))
  puts FrameworkVersion.problem(".", "1.2.3")
  assert_includes FrameworkVersion.problem(".", "1.2.3"), "spin.lock locks cybertrain 1.2.3"
  assert_includes FrameworkVersion.problem(".", "1.3.0"), "cybertrain spin lock"
  app("\">= 1.3.0\"", git_lock("1.2.3"))
  assert_includes FrameworkVersion.problem(".", "1.2.3"), "spin.lock locks cybertrain 1.2.3"
  app("\"~> 1.2.4\"", git_lock("1.3.0"))
  assert_includes FrameworkVersion.problem(".", "1.3.0"), "spin.lock locks cybertrain 1.3.0"
  app("{ features = [\"a\"], version = \"~> 1.3\" }", git_lock("1.2.3"))
  assert_includes FrameworkVersion.problem(".", "1.2.3"), "spin.lock locks cybertrain 1.2.3"
end

test "a path dependency is not checked, whatever spin.lock holds" do
  app("{ path = \"../cybertrain\" }", path_lock("1.3.0"))
  assert_equal "", FrameworkVersion.problem(".", "1.2.3")
  app("{ path = \"../cybertrain\" }", "")
  assert_equal "", FrameworkVersion.problem(".", "1.2.3")
  app("{ path = \"../cybertrain\" }", git_lock("1.3.0"))
  assert_equal "", FrameworkVersion.problem(".", "1.2.3")
  app("{ features = [\"a\"], path = \"../cybertrain\" }", git_lock("1.3.0"))
  assert_equal "", FrameworkVersion.problem(".", "1.2.3")
end

test "without a lock, the release spin.toml names is checked" do
  app(git_dep("v1.2.3"), "")
  assert_equal "", FrameworkVersion.problem(".", "1.2.3")
  app(git_dep("v1.3.0"), "")
  puts FrameworkVersion.problem(".", "1.2.3")
  app("\"1.3.0\"", "")
  assert_includes FrameworkVersion.problem(".", "1.2.3"), "cybertrain 1.3.0 (spin.toml)"
  app("{ version = \"1.3.0\" }", "")
  assert_includes FrameworkVersion.problem(".", "1.2.3"), "cybertrain 1.3.0 (spin.toml)"
end

test "a lock without [lock.cybertrain], or one left from a path dependency, is no lock" do
  app(git_dep("v1.3.0"), "[lock.redis]\nversion = \"1.2.3\"\ngit = \"https://example.com/redis\"\nref = \"#{SHA}\"\n")
  assert_includes FrameworkVersion.problem(".", "1.2.3"), "cybertrain 1.3.0 (spin.toml)"
  app(git_dep("v1.3.0"), path_lock("1.2.3"))
  assert_includes FrameworkVersion.problem(".", "1.2.3"), "cybertrain 1.3.0 (spin.toml)"
  app(git_dep("v1.2.3"), path_lock("1.3.0"))
  assert_equal "", FrameworkVersion.problem(".", "1.2.3")
end

test "without a lock, a branch, a commit, a range or no ref names no release: no check" do
  app(git_dep("main"), "")
  assert_equal "", FrameworkVersion.problem(".", "1.2.3")
  app(git_dep(SHA), "")
  assert_equal "", FrameworkVersion.problem(".", "1.2.3")
  app(git_dep("v1.3"), "")
  assert_equal "", FrameworkVersion.problem(".", "1.2.3")
  app(git_dep("v1.3.0-rc1"), "")
  assert_equal "", FrameworkVersion.problem(".", "1.2.3")
  app("{ git = \"#{GIT}\" }", "")
  assert_equal "", FrameworkVersion.problem(".", "1.2.3")
  app("\"~> 1.3\"", "")
  assert_equal "", FrameworkVersion.problem(".", "1.2.3")
  app("\">= 1.3.0\"", "")
  assert_equal "", FrameworkVersion.problem(".", "1.2.3")
end

# spin.toml as written, with no spin.lock.
def toml(text)
  File.write("spin.toml", text)
  File.delete("spin.lock") if File.exist?("spin.lock")
end

test "spin.toml is read as spin reads it: comments, spaced headers, the last line for a key" do
  toml("[dependencies] # what the app needs\ncybertrain = \"1.3.0\"\n")
  assert_includes FrameworkVersion.problem(".", "1.2.3"), "cybertrain 1.3.0 (spin.toml)"
  toml("[ dependencies ]\ncybertrain = \"1.3.0\"\n")
  assert_includes FrameworkVersion.problem(".", "1.2.3"), "cybertrain 1.3.0 (spin.toml)"
  toml("[dependencies]\ncybertrain=\"1.3.0\"   # pinned\n")
  assert_includes FrameworkVersion.problem(".", "1.2.3"), "cybertrain 1.3.0 (spin.toml)"
  toml("[dependencies]\n  cybertrain = #{git_dep("v1.3.0")} # the release\n")
  assert_includes FrameworkVersion.problem(".", "1.2.3"), "cybertrain 1.3.0 (spin.toml)"
  toml("[dependencies]\ncybertrain = \"1.2.3\"\ncybertrain = \"1.3.0\"\n")
  assert_includes FrameworkVersion.problem(".", "1.2.3"), "cybertrain 1.3.0 (spin.toml)"
  toml("[dependencies]\n# cybertrain = \"1.3.0\"\n[package]\ncybertrain = \"1.3.0\"\n")
  assert_equal "", FrameworkVersion.problem(".", "1.2.3")
end

test "an exact version spelled '0.Y.Z' or \"= 0.Y.Z\" is the release spin selects for it" do
  toml("[dependencies]\ncybertrain = '0.5.0'\n")
  assert_includes FrameworkVersion.problem(".", "0.4.0"), "cybertrain 0.5.0 (spin.toml)"
  assert_equal "", FrameworkVersion.problem(".", "0.5.0")
  toml("[dependencies]\ncybertrain = \"= 0.5.0\"\n")
  assert_includes FrameworkVersion.problem(".", "0.4.0"), "cybertrain 0.5.0 (spin.toml)"
  assert_equal "", FrameworkVersion.problem(".", "0.5.0")
  toml("[dependencies]\ncybertrain = { version = '0.5.0' }\n")
  assert_includes FrameworkVersion.problem(".", "0.4.0"), "cybertrain 0.5.0 (spin.toml)"
  # spin reads "= 1" as the number 0: the release it looks for is 0.5.0.
  toml("[dependencies]\ncybertrain = \"= 1.5.0\"\n")
  assert_includes FrameworkVersion.problem(".", "1.5.0"), "cybertrain 0.5.0 (spin.toml)"
end

test "no spin.toml, or no cybertrain dependency: no check" do
  app("", git_lock("1.3.0"))
  assert_equal "", FrameworkVersion.problem(".", "1.2.3")
  assert_equal "", FrameworkVersion.problem("no_such_dir", "1.2.3")
  File.write("spin.toml", "[package]\nname = \"blog\"\n\n[dev-dependencies]\ncybertrain = \"1.3.0\"\n")
  assert_equal "", FrameworkVersion.problem(".", "1.2.3")
end

test "the application commands stop before spin; spin and version do not check" do
  app(git_dep("v999.0.0"), git_lock("999.0.0"))
  assert_equal 1, Cybertrain::CLI.run(["db", "migrate"])
  assert_equal 1, Cybertrain::CLI.run(["migration"])
  assert_equal 1, Cybertrain::CLI.run(["build"])
  assert_equal 1, Cybertrain::CLI.run(["server", "--spinel"])
  assert_equal 1, Cybertrain::CLI.run(["test"])
  assert_equal 1, Cybertrain::CLI.run(["generate", "scaffold", "article", "title:string"])
  assert_equal 1, Cybertrain::CLI.run(["generate", "helper", "markdown"])
  refute File.exist?("app")
  refute File.exist?("db")
  refute File.exist?("build")
  # `cybertrain spin` with no arguments prints its usage: it got past the
  # check, as `cybertrain spin lock` must.
  assert_equal 1, Cybertrain::CLI.run(["spin"])
  assert_equal 0, Cybertrain::CLI.run(["version"])
end

test "an application on the command's own release, or on a path, passes the CLI's check" do
  app(git_dep("v#{Cybertrain::VERSION}"), git_lock(Cybertrain::VERSION))
  Cybertrain::CLI.require_framework_version!
  app("{ path = \"../cybertrain\" }", path_lock("999.0.0"))
  Cybertrain::CLI.require_framework_version!
  app(git_dep("v999.0.0"), "")
  assert_includes assert_raises("Cybertrain::CLI::InvalidArgument") { Cybertrain::CLI.require_framework_version! }, "cybertrain 999.0.0 (spin.toml)"
end


def concern(file, source)
  Cybertrain::Gen::ConcernScan.scan_source(file, source)
end

GATE_SOURCE = <<~'RUBY'
  module AdminGate
    extend ActiveSupport::Concern

    included do
      before_action :require_admin, only: [:index]
      helper_method :admin?
      rescue_from Forbidden, with: :forbidden
    end

    class_methods do
      def per_page = 50

      def title(name)
        "admin #{name}"
      end
    end

    def admin? = @admin == true
    def require_admin
      @gate = "closed" unless admin?
    end
  end
RUBY

test "a concern's scan: included body, class methods, includes, ivars, callbacks, defs" do
  c = concern("app/controllers/concerns/admin_gate.rb", GATE_SOURCE)
  assert_equal "AdminGate", c.concern_name
  assert_equal 1, c.concern_line
  assert_equal ["    before_action :require_admin, only: [:index]\n", "    helper_method :admin?\n", "    rescue_from Forbidden, with: :forbidden\n"], c.included_body
  assert_equal ["per_page", "title"], c.class_method_names
  assert_equal [11, 13], c.class_method_line_numbers
  assert_equal [], c.concern_includes
  assert_equal ["gate"], c.concern_ivars
  assert_equal ["require_admin", "forbidden"], c.concern_callbacks
  assert_equal ["admin?", "require_admin"], c.concern_defs.map { |d| d.name }
  assert_equal 1, c.callback_count
  assert_equal 1, c.rescue_count
  assert_nil concern("app/controllers/x.rb", "# nothing\n")
end

test "gen/concerns.rb: the class methods on the concern, a forwarder and the splice at the include" do
  gate = concern("app/controllers/concerns/admin_gate.rb", GATE_SOURCE)
  app = Cybertrain::Gen::ControllerScan.scan_source("app/controllers/application_controller.rb", "class ApplicationController < Cybertrain::Controller\nend\n")
  source = "module Admin\n  class ArticlesController < ApplicationController\n    before_action :a\n    after_action :b\n    rescue_from Gone, with: :gone\n    include AdminGate\n  end\nend\n"
  articles = Cybertrain::Gen::ControllerScan.scan_source("app/controllers/admin/articles_controller.rb", source)
  expected = <<~'RUBY'
    # Generated by `spin run gen` from app/controllers and app/models. Do not edit.
    #
    # Each concern's `class_methods do ... end` as methods of the concern, and
    # in every class that includes it a forwarder per method and the
    # concern's `included do ... end` body, at the position of the `include`
    # (Cybertrain::Controller.concern_insert_at,
    # Cybertrain::Model.model_concern_insert_at). Loaded after the
    # application's classes.

    module AdminGate
      def self.per_page = 50

      def self.title(name)
        "admin #{name}"
      end
    end

    module Admin
      class ArticlesController
        def self.per_page(...) = AdminGate.per_page(...)
        def self.title(...) = AdminGate.title(...)

        # AdminGate (include AdminGate at app/controllers/admin/articles_controller.rb:6)
        concern_insert_at(2, 1)
        before_action :require_admin, only: [:index]
        helper_method :admin?
        rescue_from Forbidden, with: :forbidden
        concern_insert_done
      end
    end
  RUBY
  assert_equal expected, Cybertrain::Gen::ConcernsEmitter.emit([app, articles], [gate])
  controllers = Cybertrain::Gen::ControllersEmitter.emit([app, articles], Cybertrain::Gen::JobsPageSpec.new("", ""), [gate])
  assert_includes controllers, "      { \"gate\" => @gate }\n"
  assert_includes controllers, "      when :a then a\n      when :b then b\n      when :gone then gone\n      when :require_admin then require_admin\n      when :forbidden then forbidden\n"
end


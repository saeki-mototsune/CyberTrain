# Pure text tests of the model generator (no database: CRuby-portable).
# The expected sources below are copied verbatim from test/model.rb, the
# hand-written executable specification of the generated shape.

def model_spec_schema
  Cybertrain::Schema.define(version: "1") do |s|
    s.create_table "posts" do |t|
      t.string "title", null: false
      t.text "body"
      t.timestamps
    end
    s.create_table "comments" do |t|
      t.references :post
      t.string "author"
      t.text "body", null: false
      t.timestamps
    end
    s.create_table "flags" do |t|
      t.boolean "active", null: false, default: "false"
      t.float "score"
      t.string "group"
    end
  end
end

def emit_for(name, view_methods = [])
  definition = model_spec_schema
  Cybertrain::Gen::ModelsEmitter.emit(definition.table(name), definition, view_methods)
end

# One line of `source` per entry, compared after stripping indentation.
def assert_lines(source, lines)
  stripped = source.lines.map { |l| l.strip }
  lines.each do |line|
    Cybertrain::Test.count_assertion
    flunk("missing line: #{line}") unless stripped.include?(line)
  end
end

def refute_line(source, line)
  Cybertrain::Test.count_assertion
  stripped = source.lines.map { |l| l.strip }
  flunk("unexpected line: #{line}") if stripped.include?(line)
end


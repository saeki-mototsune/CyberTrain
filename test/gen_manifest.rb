  draw_routes
  assert_equal 0, Cybertrain::Gen::Runner.run(ROOT, [])
end

test "runner --check passes when gen is fresh" do
  draw_routes
  assert_equal 0, Cybertrain::Gen::Runner.run(ROOT, ["--check"])
end

test "runner --check reports stale files and writes nothing" do
  Cybertrain::Routes.reset!
  Cybertrain::Routes.draw { resources :posts, only: [:index, :show] }
  File.write("#{ROOT}/gen/app.rb", "# edited by hand\n")
  assert_equal 1, Cybertrain::Gen::Runner.run(ROOT, ["--check"])
  assert_equal "# edited by hand\n", File.read("#{ROOT}/gen/app.rb")
  assert_equal 0, Cybertrain::Gen::Runner.run(ROOT, [])
  assert_equal 0, Cybertrain::Gen::Runner.run(ROOT, ["--check"])
end


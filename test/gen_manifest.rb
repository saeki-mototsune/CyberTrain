test "runner writes the gen files" do
  draw_routes
  assert_equal 0, Cybertrain::Gen::Runner.run(ROOT, [])
  assert_equal Cybertrain::Gen::Manifest.emit(ROOT), File.read("#{ROOT}/gen/app.rb")
  assert_equal Cybertrain::Gen::RoutesEmitter.emit(Cybertrain::Routes.specs), File.read("#{ROOT}/gen/routes.rb")
  controllers = File.read("#{ROOT}/gen/controllers.rb")
  assert_includes controllers, "class ApplicationController < Cybertrain::Controller\n"
  assert_includes controllers, "module Admin\n  class UsersController < ::ApplicationController\n"
  # No helper modules, components or jobs in this tree (its files are
  # all controller-like classes), and no schema: the tables are there,
  # empty, and gen/jobs.rb is its header.
  assert_equal Cybertrain::Gen::HelpersEmitter.emit([]), File.read("#{ROOT}/gen/helpers.rb")
  assert_equal Cybertrain::Gen::ComponentsEmitter.emit([]), File.read("#{ROOT}/gen/components.rb")
  assert_equal Cybertrain::Gen::JobsEmitter.emit([]), File.read("#{ROOT}/gen/jobs.rb")
  assert_equal Cybertrain::Gen::ConsoleEmitter.emit([]), File.read("#{ROOT}/gen/console.rb")
  # Concerns that nothing includes and that have no class methods: the
  # header alone.
  assert_equal Cybertrain::Gen::ConcernsEmitter.emit([], []), File.read("#{ROOT}/gen/concerns.rb")
  # Each concern is loaded from its copy under gen/concerns.
  assert_equal "module Trackable\n  extend ActiveSupport::Concern\nend\n\n" \
               "# Generated by `spin run gen` from app/controllers/concerns/trackable.rb. Do not edit.\n",
               File.read("#{ROOT}/gen/concerns/controllers/concerns/trackable.rb")
end

test "gen/app.rb requires locales after assets" do
  draw_routes
  assert_equal 0, Cybertrain::Gen::Runner.run(ROOT, [])
  manifest = File.read("#{ROOT}/gen/app.rb")
  assert_includes manifest, "require_relative \"routes\"\nrequire_relative \"assets\"\nrequire_relative \"locales\"\nrequire_relative \"../app/helpers/application_helper\"\n"
  assert_equal 1, manifest.scan("require_relative \"locales\"\n").size
  # This tree has no config/locales: gen/locales.rb is its empty tables.
  assert_equal Cybertrain::Gen::Runner.locales_source(ROOT), File.read("#{ROOT}/gen/locales.rb")
  assert_includes File.read("#{ROOT}/gen/locales.rb"), "    def self.text_table\n      h = { \"\" => \"\" }\n      h.delete(\"\")\n      h\n    end\n"
end

test "a gen/concerns file whose concern is gone is removed (reported stale by --check)" do
  draw_routes
  File.write("#{ROOT}/gen/concerns/models/concerns/gone.rb", "module Gone\nend\n")
  assert_equal 1, Cybertrain::Gen::Runner.run(ROOT, ["--check"])
  assert File.exist?("#{ROOT}/gen/concerns/models/concerns/gone.rb")
  assert_equal 0, Cybertrain::Gen::Runner.run(ROOT, [])
  refute File.exist?("#{ROOT}/gen/concerns/models/concerns/gone.rb")
  assert_equal 0, Cybertrain::Gen::Runner.run(ROOT, ["--check"])
end

test "removing a stale gen/concerns file removes the directories it leaves empty" do
  draw_routes
  Cybertrain::Gen::Runner.make_dirs("#{ROOT}/gen/concerns/models/concerns/old/deeper")
  File.write("#{ROOT}/gen/concerns/models/concerns/old/deeper/gone.rb", "module Gone\nend\n")
  assert_equal 1, Cybertrain::Gen::Runner.run(ROOT, ["--check"])
  assert File.directory?("#{ROOT}/gen/concerns/models/concerns/old/deeper")
  assert_equal 0, Cybertrain::Gen::Runner.run(ROOT, [])
  refute File.exist?("#{ROOT}/gen/concerns/models/concerns/old")
  # The directory of a concern that is still there stays.
  assert File.exist?("#{ROOT}/gen/concerns/models/concerns/sluggable.rb")
  assert_equal 0, Cybertrain::Gen::Runner.run(ROOT, ["--check"])
  # A tree whose last concern is gone loses gen/concerns itself.
  base = Dir.mktmpdir("cybertrain-gen-concerns-gone")
  Cybertrain::Gen::Runner.make_dirs("#{base}/gen/concerns/controllers/concerns")
  File.write("#{base}/gen/concerns/controllers/concerns/x.rb", "module X\nend\n")
  Cybertrain::Gen::Runner.remove_file(base, "gen/concerns/controllers/concerns/x.rb", false)
  Cybertrain::Gen::Runner.remove_empty_dirs(base, "gen/concerns/controllers/concerns", "gen/concerns")
  assert_equal [], Dir.children("#{base}/gen")
  Dir.rmdir("#{base}/gen")
  Dir.rmdir(base)
end


def hex(s)
  out = String.new
  i = 0
  while i < s.bytesize
    out << (s.getbyte(i) + 256).to_s(16).byteslice(1, 2)
    i += 1
  end
  out
end

# Binary-tagged, as a socket's bytes are.
def unhex(text)
  s = text.to_s
  out = "0" * (s.bytesize / 2)
  out.force_encoding("BINARY")
  i = 0
  while i < out.bytesize
    out.setbyte(i, s.byteslice(2 * i, 2).to_i(16))
    i += 1
  end
  out
end

# A binary-tagged copy, as bytes read from a socket are.
def binary(text)
  out = String.new
  out << text.to_s
  out.force_encoding("BINARY")
  out
end

# One packet as the server frames it.
def frame(seq, payload)
  out = Wire.int_le(payload.bytesize, 3)
  out << Wire.int_le(seq, 1)
  out << payload
  out
end

# A peer that answers from a script and records what the client sends.
class ScriptStream < Cybertrain::Net::Stream
  def initialize(script)
    @script_in = String.new
    @script_in << script
    @script_pos = 0
    @script_out = String.new
  end

  def stream_read(max, timer)
    left = @script_in.bytesize - @script_pos
    return "" if left <= 0

    n = left < max ? left : max
    out = @script_in.byteslice(@script_pos, n)
    @script_pos += n
    out
  end

  def stream_write(data, timer)
    @script_out << data
    nil
  end

  def stream_label
    "fake:3306"
  end

  def script_sent
    @script_out
  end

  def script_left
    @script_in.bytesize - @script_pos
  end
end

# A Protocol over a stream that answers with the concatenated hex records.
def protocol_for(stream)
  Protocol.new(PacketIO.new(stream))
end

def stream_of(hex_text)
  ScriptStream.new(unhex(hex_text))
end

# An ERR packet's payload in the layout of the recorded ones.
def err_packet(code, state, message)
  out = unhex("ff")
  out << Wire.int_le(code, 2)
  out << "#"
  out << binary(state)
  out << binary(message)
  out
end

# The class and message a query raised, or "nothing raised". The rescue
# is here, in a method that does not yield (NOTES rule 32).
def query_failure(stream, sql)
  proto = protocol_for(stream)
  got = "nothing raised"
  begin
    proto.query(sql)
  rescue Cybertrain::DB::Error => e
    got = "#{e.class.name}: #{e.message}"
  end
  got
end


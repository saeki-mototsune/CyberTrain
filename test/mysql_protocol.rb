  assert_equal "", CLOSE_RESP
  assert_equal "Cybertrain::DB::Error: MySQL: statement 5 is not prepared on this connection", param_count_failure(proto, id)
end

test "ping answers true for OK and false when the connection is gone; quit sends COM_QUIT" do
  stream = stream_of(PING_RESP)
  proto = protocol_for(stream)
  assert_equal true, proto.ping
  assert_equal PING_REQ, hex(stream.script_sent)
  assert_equal false, protocol_for(ScriptStream.new("")).ping
  # An ERR answer is false too, not an exception.
  assert_equal false, protocol_for(ScriptStream.new(frame(1, err_packet(1105, "HY000", "Unknown error")))).ping
  quitting = ScriptStream.new("")
  assert_nil protocol_for(quitting).quit
  assert_equal QUIT_REQ, hex(quitting.script_sent)
  assert_equal "", QUIT_RESP
end

test "a BIGINT UNSIGNED past 2**63 - 1 is refused once the result is read, in both protocols" do
  stream = stream_of(UNSIGNED_MAX_TEXT_RESP + PING_RESP)
  proto = protocol_for(stream)
  got = "nothing raised"
  begin
    proto.query("SELECT CAST(18446744073709551615 AS UNSIGNED) AS big")
  rescue Cybertrain::DB::Error => e
    got = "#{e.class.name}: #{e.message}"
  end
  assert_equal "Cybertrain::DB::Error: MySQL: column 'big' holds a BIGINT UNSIGNED value past 2**63 - 1, which an Integer cannot hold", got
  assert_equal true, proto.ping
  binary = stream_of(UNSIGNED_PREPARE_RESP + UNSIGNED_EXECUTE_RESP + PING_RESP)
  bproto = protocol_for(binary)
  id = bproto.prepare("SELECT CAST(18446744073709551615 AS UNSIGNED) AS big")
  assert_equal "Cybertrain::DB::Error: MySQL: column 'big' holds a BIGINT UNSIGNED value past 2**63 - 1, which an Integer cannot hold",
               execute_failure(bproto, id, [])
  assert_equal true, bproto.ping
  assert_equal 0, binary.script_left
end

test "zero dates decode as zeros in both protocols" do
  text = protocol_for(stream_of(ZERO_TEXT_RESP)).query("SELECT * FROM t_zero")
  assert_equal [["0000-00-00", "0000-00-00 00:00:00.000000"]], text.result_rows
  assert_equal [false, true], text.datetime_columns
  stream = stream_of(ZERO_PREPARE_RESP + ZERO_EXECUTE_RESP)
  proto = protocol_for(stream)
  id = proto.prepare("SELECT * FROM t_zero")
  binary = proto.execute_statement(id, [])
  assert_equal [["0000-00-00", "0000-00-00 00:00:00.000000"]], binary.result_rows
end


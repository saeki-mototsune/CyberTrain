# packets, multi-statements), COM_STMT_PREPARE / EXECUTE / CLOSE (binary
# rows, the bind layout), COM_PING and COM_QUIT, each column type's Ruby
# value, and ERR packets mapped to the DB::Error classes. The real PacketIO
# reads from a scripted stream; no sockets.
#
# How the packets were recorded (2026-11-27, once): script/mysql-dev
# started mysql:8.0 (8.0.46, --default-time-zone=+09:00); a CRuby script
# outside the repository connected over plain TCP to 127.0.0.1:33306
# (ssl_mode=disabled, mysql_native_password, the capabilities auth.rb
# asks for, database cybertrain_test), created and filled the tables
# below, then for each exchange wrote the request (framed, sequence 0)
# and kept every byte the server sent until it was quiet for 0.5 s (3 s
# for the lock wait). *_REQ is what the client sent (hex), *_RESP what the
# server answered. The session's sql_mode was the one Task 7 sets
# (STRICT_ALL_TABLES, NO_ZERO_DATE, ...); t_zero was filled under
# sql_mode ''. The tables:
#
#   t_types (id INT PRIMARY KEY, c_tiny TINYINT, c_short SMALLINT,
#     c_int24 MEDIUMINT, c_long INT, c_longlong BIGINT, c_ulonglong BIGINT
#     UNSIGNED, c_year YEAR, c_float FLOAT, c_double DOUBLE, c_decimal
#     DECIMAL(10,2), c_date DATE, c_datetime DATETIME(6), c_timestamp
#     TIMESTAMP(6) NULL, c_datetime0 DATETIME, c_json JSON, c_blob BLOB,
#     c_varchar VARCHAR(50), c_text TEXT, c_time TIME(6), c_utiny TINYINT
#     UNSIGNED): rows 1 and 3 as TYPES_ROW1 / TYPES_ROW3 below, row 2 NULL
#     but its id.
#   t_wide (id INT PRIMARY KEY, c1 .. c9 INT): five rows 1..9 with one
#     NULL each, in c6, c7, c8, c9 and c1.
#   t_auto (id BIGINT AUTO_INCREMENT PRIMARY KEY, v VARCHAR(10)),
#   t_many (id INT PRIMARY KEY, v INT) with 300 rows,
#   t_parent (id INT PRIMARY KEY) holding 1, t_child (id INT PRIMARY KEY,
#     parent_id INT REFERENCES t_parent) holding (1, 1),
#   t_binds (id INT AUTO_INCREMENT PRIMARY KEY, i BIGINT, f DOUBLE,
#     s VARCHAR(20), n INT, b BLOB), t_lock (id INT PRIMARY KEY, v INT),
#   t_zero (d DATE, dt DATETIME(6)) holding the zero date and datetime.

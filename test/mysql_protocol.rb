# Compares a decoded row with the expected one cell by cell; the cell at
# `blob_at` (-1: none) is compared as hex, its bytes being binary.
def assert_row(expected, actual, blob_at)
  assert_equal expected.size, actual.size
  i = 0
  while i < expected.size
    if i == blob_at
      assert_equal expected[i], hex(actual[i].to_s)
    else
      assert_equal expected[i], actual[i]
    end
    i += 1
  end
end

